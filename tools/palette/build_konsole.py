"""Generate the Nisse Konsole color scheme from assets/palette/ember.json.

    python tools/palette/build_konsole.py         # writes assets/theme/konsole/NisseEmber.colorscheme

The scheme is generated output: edit the tokens or this script, never the .colorscheme file. The Konsole profile next to
it (Nisse.profile) is a plain hand-written file that names this scheme.
"""
import sys
from pathlib import Path

import contrast

OUT_DIR = Path(__file__).resolve().parents[2] / "assets" / "theme" / "konsole"
NAMES = ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"]


def rgb(hex_value):
    return ",".join(str(c) for c in contrast.rgb(hex_value))


def build(pal):
    """Return {section: {key: value}} in Konsole's .colorscheme layout."""
    t = {k: v["hex"] for k, v in pal["terminal"].items()}
    scheme = {
        "Background": {"Color": rgb(t["bg"])},
        "BackgroundIntense": {"Color": rgb(t["bg"])},
        "Foreground": {"Color": rgb(t["fg"])},
        "ForegroundIntense": {"Color": rgb(t["bright-white"])},
    }
    for i, name in enumerate(NAMES):
        scheme[f"Color{i}"] = {"Color": rgb(t[name])}
        scheme[f"Color{i}Intense"] = {"Color": rgb(t["bright-" + name])}
    scheme["General"] = {"Blur": "false", "ColorRandomization": "false", "Description": "Nisse Ember", "Opacity": "1"}
    return scheme


def render(scheme):
    lines = ["# SPDX-License-Identifier: GPL-2.0-or-later",
             "# Generated by tools/palette/build_konsole.py from assets/palette/ember.json. Do not edit by hand.", ""]
    for section, keys in scheme.items():
        lines.append(f"[{section}]")
        lines.extend(f"{k}={v}" for k, v in keys.items())
        lines.append("")
    return "\n".join(lines)


def main():
    pal = contrast.load()
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    path = OUT_DIR / "NisseEmber.colorscheme"
    path.write_text(render(build(pal)), encoding="ascii", newline="\n")
    print("wrote", path)


if __name__ == "__main__":
    sys.exit(main())
