"""N-402, round 4: four minimalist tomte, simplified to the logo's language.

Bert's verdict on round 3: the heads sat too far from the bodies, the beards did not match the head widths, and the
mascot should be simple and minimal like the logo. The rules this round follows (they become the style guide):
  - ONE width per gnome: the cap base, the face and the top of the beard are the same width
  - the head touches the body: no neck gap; the beard either IS the body or overlaps it
  - flat shapes only: the logo's hooked cap, circles, rounded rectangles; no brows, cheeks, belts, hems, shading, goggles
  - at most six palette colors in any drawing (tested)
Scripted SVG, Ember palette hexes only, no gradients or filters.

    python tools/art/mascot_round4.py            writes assets/art/mascot-round4/*.svg, sheet.png
"""
import base64
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from mascot_options import (DIV, EMBER, EMBER_P, EMBER_T, FIG_H, FIG_W, HEAD_BOX, INK, MUTED, OUTL,  # noqa: E402
                            PAPER, SURF, SURF2)
from mascot_round2 import CURL  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "assets" / "art" / "mascot-round4"

HEADER = '<?xml version="1.0" encoding="UTF-8"?>\n<!-- SPDX-License-Identifier: GPL-2.0-or-later -->\n' \
         '<!-- Generated by tools/art/mascot_round4.py (N-402 round 4). Ember palette only. -->\n'

PICK_HALF_SPAN = 73   # the pick head spans 146 units: a point 62 to the left and a point 84 to the right
TILT = 6.0            # degrees the pickaxe leans


def doc(w, h, title, body, defs=""):
    d = f"  <defs>{defs}</defs>\n" if defs else ""
    return (HEADER + f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}" '
            f'role="img" aria-label="{title}">\n  <title>{title}</title>\n{d}  {body}\n</svg>\n')


# ------------------------------------------------------------------ geometry: one width per gnome
def specs():
    """Per option: the one width (cap, face, beard) and where the head ends and the body begins (y)."""
    return {
        "1": dict(name="stack", cap_w=150, face_w=150, beard_w=150, cap_base=252, head_bottom=282, body_top=282,
                  pick_x=300, hand_l=(118, 432)),
        "2": dict(name="robe", cap_w=150, face_w=150, beard_w=150, cap_base=205, head_bottom=352, body_top=320,
                  pick_x=300, hand_l=(106, 432)),
        "3": dict(name="gumdrop", cap_w=180, face_w=180, beard_w=180, cap_base=326, head_bottom=326, body_top=322,
                  pick_x=312, hand_l=(106, 440)),
        "4": dict(name="sticker", cap_w=150, face_w=150, beard_w=150, cap_base=252, head_bottom=282, body_top=282,
                  pick_x=300, hand_l=(118, 432)),
    }


def cap_top(n):
    sp = specs()[n]
    return sp["cap_base"] - 192 * sp["cap_w"] / 170


# ------------------------------------------------------------------ parts
def cap(w, base_y, cx=200):
    """The logo's hooked cap as one flat Ember shape standing on base_y."""
    return (f'<path d="{CURL}" fill="{EMBER}" transform="translate({cx - w / 2:.1f} {base_y}) scale({w / 170:.4f})"/>')


def beard_body(w, top, bottom, fill, cx=200):
    """A beard of constant width w: a scooped top edge, straight sides, a round bottom."""
    x0, x1 = cx - w / 2, cx + w / 2
    return (f'<path d="M{x0} {top} Q{cx} {top + 26} {x1} {top} L{x1} {bottom - 60} C{x1} {bottom - 10} {cx + w * 0.24:.0f} {bottom} {cx} {bottom} '
            f'C{cx - w * 0.24:.0f} {bottom} {x0} {bottom - 10} {x0} {bottom - 60} Z" fill="{fill}"/>')


def dots(y, dx, r, fill):
    return f'<circle cx="{200 - dx}" cy="{y}" r="{r}" fill="{fill}"/><circle cx="{200 + dx}" cy="{y}" r="{r}" fill="{fill}"/>'


def boots(y, spread=30, fill=EMBER_P):
    return (f'<ellipse cx="{200 - spread}" cy="{y}" rx="28" ry="13" fill="{fill}"/>'
            f'<ellipse cx="{200 + spread}" cy="{y}" rx="28" ry="13" fill="{fill}"/>')


def pick(x, y, length, head=MUTED, tilt=TILT):
    """Group id pickaxe: a handle and one flat steel head, a thick crescent that tapers to a point at each end."""
    d = (f"M{x - 62} {y + 20} C{x - 34} {y - 44} {x + 40} {y - 44} {x + 84} {y + 20} "
         f"C{x + 40} {y} {x - 34} {y} {x - 62} {y + 20} Z")
    return (f'<g id="pickaxe" transform="rotate({tilt} {x} {y})">'
            f'<line x1="{x}" y1="{y - 4}" x2="{x}" y2="{y + length}" stroke="{EMBER_P}" stroke-width="15" stroke-linecap="round"/>'
            f'<path d="{d}" fill="{head}"/></g>')


def along(x, y_top, d, tilt=TILT):
    t = math.radians(tilt)
    return x - d * math.sin(t), y_top + d * math.cos(t)


def hand(x, y, r=15):
    return f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{r}" fill="{EMBER_T}"/>'


# ------------------------------------------------------------------ the four gnomes: head and body art (no feet, no hands, no pick)
def art_stack():
    """1: the beard IS the body. Cap, a small band of face, a beard that runs to the feet."""
    sp = specs()["1"]
    w = sp["cap_w"]
    return (f'<rect x="{200 - w / 2}" y="244" width="{sp["face_w"]}" height="52" rx="18" fill="{EMBER_T}"/>'
            + beard_body(sp["beard_w"], sp["body_top"], 534, PAPER)
            + f'<circle cx="200" cy="290" r="17" fill="{EMBER}"/>' + dots(266, 30, 8, INK) + cap(w, sp["cap_base"]))


def art_robe():
    """2: a round-cornered head on a robe; the beard overlaps the robe so nothing floats."""
    sp = specs()["2"]
    w = sp["cap_w"]
    return (f'<path d="M{200 - w / 2} {sp["body_top"]} L{200 + w / 2} {sp["body_top"]} L302 520 Q200 540 98 520 Z" fill="{OUTL}"/>'
            f'<rect x="{200 - w / 2}" y="157" width="{sp["face_w"]}" height="150" rx="44" fill="{EMBER_T}"/>'
            + beard_body(sp["beard_w"], 262, sp["head_bottom"], PAPER)
            + f'<circle cx="200" cy="264" r="17" fill="{EMBER}"/>' + dots(236, 30, 8, INK) + cap(w, sp["cap_base"]))


def art_gumdrop():
    """3: the smallest set of parts: cap, two eyes, a nose, a round beard-body."""
    sp = specs()["3"]
    w = sp["cap_w"]
    return (beard_body(sp["beard_w"], sp["body_top"], 534, PAPER)
            + f'<circle cx="200" cy="{sp["cap_base"] + 58}" r="20" fill="{EMBER_T}"/>' + dots(sp["cap_base"] + 26, 34, 9, INK)
            + cap(w, sp["cap_base"]))


def art_sticker():
    """4: the logo's own look: a Paper disc, the figure in Ink with the Ember cap, like the cap cut-out of the mark."""
    sp = specs()["4"]
    w = sp["cap_w"]
    return (f'<rect x="{200 - w / 2}" y="244" width="{sp["face_w"]}" height="52" rx="18" fill="{EMBER_T}"/>'
            + beard_body(sp["beard_w"], sp["body_top"], 534, INK)
            + f'<circle cx="200" cy="290" r="17" fill="{EMBER}"/>' + dots(266, 30, 8, INK) + cap(w, sp["cap_base"]))


DISC4 = f'<circle cx="200" cy="350" r="200" fill="{PAPER}"/><path d="M12 452 Q200 420 388 452" fill="none" stroke="{INK}" stroke-width="7" stroke-linecap="round"/>'

OPTIONS = {
    "1": (art_stack, boots(538), "", dict(head=MUTED), SURF, 1.45),
    "2": (art_robe, boots(536, 36), "", dict(head=OUTL), SURF, 1.45),
    "3": (art_gumdrop, boots(540), "", dict(head=MUTED), SURF, 1.3),
    "4": (art_sticker, boots(538), DISC4, dict(head=OUTL), PAPER, 1.45),
}


def figure(n, wave=False):
    art, feet, back, pk, _, _ = OPTIONS[n]
    sp = specs()[n]
    px, py, length = sp["pick_x"], 326, 224
    hx, hy = along(px, py, 104)
    lx, ly = sp["hand_l"]
    if wave:
        right = (f'<line x1="272" y1="402" x2="318" y2="352" stroke="{EMBER_T}" stroke-width="20" stroke-linecap="round"/>'
                 + hand(318, 350, 18) + f'<path d="M352 326 Q366 344 358 366" fill="none" stroke="{OUTL}" stroke-width="5" stroke-linecap="round"/>'
                 f'<path d="M366 310 Q388 338 376 372" fill="none" stroke="{OUTL}" stroke-width="5" stroke-linecap="round"/>')
        title = f"nisse gnome round 4 option {n}, figure: {sp['name']}, waving"
    else:
        right = pick(px, py, length, **pk) + hand(hx, hy)
        title = f"nisse gnome round 4 option {n}, figure: {sp['name']}, with a pickaxe"
    return doc(FIG_W, FIG_H, title, back + feet + art() + hand(lx, ly) + right)


NO_HILL = {"2"}  # the robe already gives the badge a base; a hill too would break the six-color budget


def badge(n):
    art, _, back, _, disc, s = OPTIONS[n]
    sp = specs()[n]
    ty = 40 - cap_top(n) * s
    clip = '<clipPath id="disc"><circle cx="256" cy="256" r="236"/></clipPath>'
    hill = "" if (disc == PAPER or n in NO_HILL) else (f'<path d="M0 410 C120 380 200 372 256 374 C330 376 400 384 512 420 V512 H0 Z" fill="{SURF2}"/>')
    body = (f'<circle cx="256" cy="256" r="236" fill="{disc}"/>\n  <g clip-path="url(#disc)">{hill}'
            f'<g transform="translate({256 - 200 * s:.1f} {ty:.1f}) scale({s})">{art()}</g></g>')
    return doc(HEAD_BOX, HEAD_BOX, f"nisse gnome round 4 option {n}, head badge: {sp['name']}", body, clip)


def build_all():
    out = {}
    for n in OPTIONS:
        out[f"{n}-head"] = badge(n)
        out[f"{n}-figure"] = figure(n)
    out["1-wave"] = figure("1", wave=True)
    return out


def _inner(svg):
    start = svg.index("<defs>") if "<defs>" in svg else svg.index("<title>")
    return svg[start:svg.rindex("</svg>")]


SHEET_W, SHEET_H = 1840, 1560


def build_sheet():
    col_w, margin, row_h = 440, 40, 800
    allsvg = build_all()
    parts = []
    for i, n in enumerate(OPTIONS):
        x0 = margin + i * col_w
        head_inner = _inner(allsvg[f"{n}-head"]).replace('id="disc"', f'id="disc-{n}"').replace("url(#disc)", f"url(#disc-{n})")
        parts.append(
            f'<g transform="translate({x0 + 105} 90) scale(0.45)">{head_inner}</g>'
            f'<g transform="translate({x0 + 76} 334) scale(0.74)">{_inner(allsvg[f"{n}-figure"])}</g>'
            f'<text x="{x0 + 30}" y="70" font-family="Nunito, sans-serif" font-size="54" font-weight="800" fill="{PAPER}">{n}</text>'
            f'<text x="{x0 + 100}" y="70" font-family="Nunito, sans-serif" font-size="30" fill="{MUTED}">{specs()[n]["name"]}</text>')
    y0 = row_h
    parts.append(f'<g transform="translate({margin + 76} {y0 + 70}) scale(0.74)">{_inner(allsvg["1-wave"])}</g>'
                 f'<text x="{margin + 30}" y="{y0 + 56}" font-family="Nunito, sans-serif" font-size="30" fill="{MUTED}">1 stack, waving</text>')
    for bg, ty in ((SURF, y0 + 60), (PAPER, y0 + 290)):
        parts.append(f'<rect x="{margin + 470}" y="{ty}" width="1290" height="200" fill="{bg}"/>')
        x = margin + 490
        for n in OPTIONS:
            inner = _inner(allsvg[f"{n}-head"]).replace('id="disc"', f'id="disc-{n}"').replace("url(#disc)", f"url(#disc-{n})")
            for w in (96, 48, 24):
                parts.append(f'<g transform="translate({x} {ty + 24 + (96 - w) / 2:.0f}) scale({w / 512:.4f})">{inner}</g>')
                x += w + 10
            x += 34
        parts.append(f'<text x="{margin + 490}" y="{ty + 170}" font-family="Nunito, sans-serif" font-size="22" fill="{MUTED if bg == SURF else DIV}">'
                     f'avatar sizes 96, 48 and 24 px</text>')
    body = f'<rect width="{SHEET_W}" height="{SHEET_H}" fill="{INK}"/>' + "".join(parts)
    return doc(SHEET_W, SHEET_H, "nisse gnome mascot, round 4: four minimalist tomte and a waving pose", body)


def main():
    from playwright.sync_api import sync_playwright
    OUT.mkdir(parents=True, exist_ok=True)
    for name, svg in build_all().items():
        (OUT / f"{name}.svg").write_text(svg, encoding="ascii", newline="\n")
    sheet = build_sheet()
    (OUT / "sheet.svg").write_text(sheet, encoding="ascii", newline="\n")
    uri = "data:image/svg+xml;base64," + base64.b64encode(sheet.encode("ascii")).decode()
    with sync_playwright() as p:
        b = p.chromium.launch()
        pg = b.new_page(viewport={"width": SHEET_W, "height": SHEET_H})
        pg.set_content(f'<html><body style="margin:0"><img src="{uri}" width="{SHEET_W}" height="{SHEET_H}" style="display:block"></body></html>')
        pg.wait_for_function("document.images[0].complete")
        (OUT / "sheet.png").write_bytes(pg.screenshot(clip={"x": 0, "y": 0, "width": SHEET_W, "height": SHEET_H}))
        b.close()
    print(f"wrote {len(build_all())} drawings, sheet.svg and sheet.png to {OUT}")


if __name__ == "__main__":
    sys.exit(main())
