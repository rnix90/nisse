"""N-407: the nisse wallpaper: one flat Scandinavian landscape, drawn for any screen shape, in a light and a dark look.

A cartoon Nordic scene made only of flat shapes from the Ember palette: a disc for the sun or moon (the logo's disc), layered
snow-capped mountains, a lake with ripples and the sun's reflection, a hill whose line is the logo's horizon curve, firs, and a
falu-red cottage (Ember) with lit windows. Light and dark are the SAME scene with only the colors changed.

The picture is drawn in units of 1/900 of the screen height (or of 1/1200 of the width on a portrait screen), anchored to the
bottom, so every shape of screen gets the same scene: a wider screen shows more land (more peaks and firs), not a stretched
picture. Plasma wants a folder `contents/images/WIDTHxHEIGHT.png` and `contents/images_dark/WIDTHxHEIGHT.png` (verified in
the image: Fedora's Next wallpaper has exactly that); `package_files()` lists it.

    python tools/art/wallpaper.py           writes the review sheet and the 16:9 masters to assets/art/wallpaper/
    python tools/art/wallpaper.py --all     also renders the whole Plasma wallpaper folder to out/wallpapers/nisse/
"""
import base64
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "assets" / "art" / "wallpaper"
LF = chr(10)
COLOR_BUDGET = 16

HEADER = ('<?xml version="1.0" encoding="UTF-8"?>' + LF + '<!-- SPDX-License-Identifier: GPL-2.0-or-later -->' + LF
          + '<!-- Generated by tools/art/wallpaper.py (N-407). Ember palette only, flat shapes. -->' + LF)

# the screen shapes Plasma should find a picture for (16:9, 16:10, 21:9, 4:3, 3:2 Surface, portrait)
SIZES = [(1280, 720), (1920, 1080), (2560, 1440), (3840, 2160), (5120, 2880),
         (1280, 800), (1920, 1200), (2560, 1600), (3840, 2400),
         (2560, 1080), (3440, 1440), (5120, 2160),
         (1024, 768), (2048, 1536), (2736, 1824), (1080, 1920), (1440, 2960)]

# roles -> Ember palette hex. The same roles in both looks.
DARK = {
    "sky": "#1b2330", "halo-outer": "#222c3b", "halo-inner": "#2b3749", "sun": "#f6f2e9",
    "mtn-far": "#354156", "snow-far": "#aab1bd", "mtn-mid": "#2b3749", "snow-mid": "#7a8699",
    "lake": "#222c3b", "ripple": "#354156", "reflection": "#f6f2e9",
    "shore": "#1b2330", "hill": "#2b3749", "ground": "#222c3b", "fir": "#1b2330",
    "cottage": "#e0623f", "roof": "#1b2330", "trim": "#f6f2e9", "window": "#f28463", "door": "#bd573c", "chimney": "#bd573c",
}
LIGHT = {
    "sky": "#fffdf8", "halo-outer": "#fffdf8", "halo-inner": "#f6f2e9", "sun": "#e0623f",
    "mtn-far": "#aab1bd", "snow-far": "#f6f2e9", "mtn-mid": "#7a8699", "snow-mid": "#aab1bd",
    "lake": "#aab1bd", "ripple": "#7a8699", "reflection": "#e0623f",
    "shore": "#354156", "hill": "#5d6573", "ground": "#354156", "fir": "#1b2330",
    "cottage": "#e0623f", "roof": "#1b2330", "trim": "#fffdf8", "window": "#fffdf8", "door": "#bd4525", "chimney": "#bd4525",
}
MODES = {"dark": DARK, "light": LIGHT}


def cottage_width(height):
    """The cottage's width in pixels on a screen of this height (150 units of 1/900 of the height)."""
    return 150 * height / 900


class Rng:
    """A tiny deterministic random source, so the same screen shape always gives the same picture."""

    def __init__(self, seed):
        self.state = seed

    def next(self):
        self.state = (self.state * 1103515245 + 12345) % 2147483648
        return self.state / 2147483648

    def between(self, lo, hi):
        return lo + (hi - lo) * self.next()


def f1(v):
    return f"{v:.1f}"


def pts(points):
    return " ".join(f"{f1(x)},{f1(y)}" for x, y in points)


def fir(x, base, h):
    """A tiered fir: one flat polygon."""
    w = 0.5 * h
    p = [(x, base - h), (x + 0.22 * w, base - 0.62 * h), (x + 0.12 * w, base - 0.62 * h), (x + 0.34 * w, base - 0.34 * h),
         (x + 0.2 * w, base - 0.34 * h), (x + 0.5 * w, base), (x - 0.5 * w, base), (x - 0.2 * w, base - 0.34 * h),
         (x - 0.34 * w, base - 0.34 * h), (x - 0.12 * w, base - 0.62 * h), (x - 0.22 * w, base - 0.62 * h)]
    return f'<polygon points="{pts(p)}"/>'


def lerp(a, b, t):
    return (a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t)


def mountains(rng, wu, base, hmin, hmax, color, snow_color, snow, spacing):
    """A band of peaks across the width: one polygon, plus a snow cap on each peak when `snow`."""
    peaks, x = [], -spacing * rng.between(0.2, 0.9)
    while x < wu + spacing:
        peaks.append((x, base - rng.between(hmin, hmax)))
        x += spacing * rng.between(0.8, 1.25)
    ridge = [(peaks[0][0] - spacing * 0.6, base)]
    valleys = []
    for i, p in enumerate(peaks):
        if i:
            q = peaks[i - 1]
            v = ((p[0] + q[0]) / 2, base - rng.between(0.1, 0.32) * min(base - p[1], base - q[1]))
            valleys.append(v)
            ridge.append(v)
        ridge.append(p)
    ridge.append((peaks[-1][0] + spacing * 0.6, base))
    out = [f'<polygon points="{pts(ridge)}" fill="{color}" stroke="{color}" stroke-width="10" stroke-linejoin="round"/>']
    if snow:
        for i, p in enumerate(peaks):
            left = valleys[i - 1] if i else (p[0] - spacing * 0.6, base)
            right = valleys[i] if i < len(valleys) else (p[0] + spacing * 0.6, base)
            lp, rp = lerp(p, left, 0.36), lerp(p, right, 0.36)
            d = max(lp[1], rp[1]) - p[1]
            cap = [p, rp, (p[0] + (rp[0] - p[0]) * 0.45, rp[1] - 0.12 * d), (p[0] + (rp[0] - p[0]) * 0.1, rp[1] + 0.05 * d),
                   (p[0] - (p[0] - lp[0]) * 0.4, lp[1] - 0.10 * d), lp]
            out.append(f'<polygon points="{pts(cap)}" fill="{snow_color}" stroke="{snow_color}" stroke-width="6" stroke-linejoin="round"/>')
    return "".join(out)


def hill_height(x, cx):
    """The hill's height above the bottom edge at x: a big bump on the left (the cottage) falling to the right."""
    return 105 + 135 * math.exp(-(((x - (cx - 300)) / 330) ** 2)) + 22 * math.exp(-(((x - (cx + 340)) / 240) ** 2))


def cottage(x, y, pal):
    """A falu-red cottage standing on (x, y): body, gabled roof, chimney, trim, door and two lit windows."""
    body = f'<rect x="{f1(x - 75)}" y="{f1(y - 100)}" width="150" height="100" fill="{pal["cottage"]}"/>'
    roof = f'<polygon points="{pts([(x - 94, y - 98), (x + 94, y - 98), (x, y - 168)])}" fill="{pal["roof"]}" stroke="{pal["roof"]}" stroke-width="6" stroke-linejoin="round"/>'
    chimney = f'<rect x="{f1(x + 34)}" y="{f1(y - 168)}" width="18" height="42" fill="{pal["chimney"]}"/>'
    trim = (f'<rect x="{f1(x - 75)}" y="{f1(y - 100)}" width="9" height="100" fill="{pal["trim"]}"/>'
            f'<rect x="{f1(x + 66)}" y="{f1(y - 100)}" width="9" height="100" fill="{pal["trim"]}"/>')
    windows = "".join(f'<rect x="{f1(wx - 3)}" y="{f1(y - 73)}" width="32" height="36" fill="{pal["trim"]}"/>'
                      f'<rect x="{f1(wx)}" y="{f1(y - 70)}" width="26" height="30" fill="{pal["window"]}"/>' for wx in (x - 54, x + 26))
    door = f'<rect x="{f1(x - 13)}" y="{f1(y - 60)}" width="26" height="60" fill="{pal["door"]}"/>'
    return f'<g id="cottage">{body}{trim}{chimney}{roof}{windows}{door}</g>'


def scene(w, h, mode):
    """The whole picture for a screen of w x h pixels in the "dark" or "light" look (an SVG document)."""
    pal = MODES[mode]
    s = min(h / 900, w / 1200)
    wu, hu = w / s, h / s
    cx = wu / 2

    def y(offset):               # a height above the bottom edge, in units
        return hu - offset

    rng = Rng(w * 31 + h * 17)
    sun_x, sun_y = cx + 190, y(660)
    sun = (f'<g id="sun"><circle cx="{f1(sun_x)}" cy="{f1(sun_y)}" r="300" fill="{pal["halo-outer"]}"/>'
           f'<circle cx="{f1(sun_x)}" cy="{f1(sun_y)}" r="190" fill="{pal["halo-inner"]}"/>'
           f'<circle cx="{f1(sun_x)}" cy="{f1(sun_y)}" r="105" fill="{pal["sun"]}"/></g>')
    far = f'<g id="mountains-far">{mountains(rng, wu, y(300), 150, 250, pal["mtn-far"], pal["snow-far"], True, 330)}</g>'
    mid = f'<g id="mountains-mid">{mountains(rng, wu, y(290), 70, 170, pal["mtn-mid"], pal["snow-mid"], False, 260)}</g>'
    shore_trees = "".join(fir(xx, y(282), rng.between(30, 58)) for xx in [i * 26 + rng.between(0, 14) for i in range(int(wu / 26) + 2)])
    shore = f'<g id="shore" fill="{pal["shore"]}">{shore_trees}</g>'
    lake_top, lake_bottom = y(285), y(100)
    ripples = "".join(f'<line x1="{f1(rx)}" y1="{f1(ry)}" x2="{f1(rx + rl)}" y2="{f1(ry)}" stroke="{pal["ripple"]}" stroke-width="5" stroke-linecap="round"/>'
                      for rx, ry, rl in ((rng.between(0, wu), rng.between(lake_top + 25, lake_bottom - 12), rng.between(40, 130)) for _ in range(int(wu / 70))))
    reflection = "".join(f'<rect x="{f1(sun_x - rw / 2)}" y="{f1(lake_top + 18 + i * 26)}" width="{rw}" height="9" rx="4.5" fill="{pal["reflection"]}"/>'
                         for i, rw in enumerate((150, 110, 76, 48)))
    lake = (f'<g id="lake"><rect x="0" y="{f1(lake_top)}" width="{f1(wu)}" height="{f1(lake_bottom - lake_top + 2)}" fill="{pal["lake"]}"/>'
            f'{ripples}{reflection}</g>')
    xs = [i * 24 - 12 for i in range(int(wu / 24) + 3)]
    curve = [(xx, y(hill_height(xx, cx))) for xx in xs]
    hill_path = "M" + " L".join(f"{f1(a)} {f1(b)}" for a, b in curve) + f" L{f1(xs[-1])} {f1(hu)} L{f1(xs[0])} {f1(hu)} Z"
    hill = f'<path id="hill" d="{hill_path}" fill="{pal["hill"]}" stroke="{pal["hill"]}" stroke-width="6" stroke-linejoin="round"/>'
    cot_x = cx - 300
    cot = cottage(cot_x, y(hill_height(cot_x, cx)) + 2, pal)
    slope = []
    for xx in [i * 62 + rng.between(0, 24) for i in range(int(wu / 62) + 1)]:
        if abs(xx - cot_x) > 130:
            slope.append(fir(xx, y(hill_height(xx, cx)) + 6, rng.between(58, 120)))
    slope_firs = f'<g id="firs-slope" fill="{pal["fir"]}">{"".join(slope)}</g>'
    ground = f'<rect id="ground" x="0" y="{f1(y(90))}" width="{f1(wu)}" height="90" fill="{pal["ground"]}"/>'
    edge = []
    for k, hgt in enumerate((330, 250, 380, 210)):                       # tall firs at the left and right edges
        edge.append(fir(30 + k * 64, y(44), hgt))
        edge.append(fir(wu - 34 - k * 66, y(44), hgt * 0.92))
    near = f'<g id="firs-near" fill="{pal["fir"]}">{"".join(edge)}</g>'
    body = (f'<g transform="scale({s:.5f})"><rect id="sky" width="{f1(wu)}" height="{f1(hu)}" fill="{pal["sky"]}"/>'
            f'{sun}{far}{mid}{shore}{lake}{hill}{cot}{slope_firs}{ground}{near}</g>')
    label = f"nisse wallpaper, {mode}, {w} by {h}"
    return (HEADER + f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}" role="img" '
            f'aria-label="{label}">' + LF + f'  <title>{label}</title>' + LF + f'  {body}' + LF + '</svg>' + LF)


def metadata():
    meta = {"KPlugin": {"Authors": [{"Name": "nisse"}], "Id": "nisse", "Name": "nisse", "License": "GPL-2.0-or-later",
                        "Description": "A Scandinavian landscape with a falu-red cottage, in a light and a dark look"}}
    return json.dumps(meta, indent=4) + LF


def package_files():
    """Every file of the Plasma wallpaper folder (relative paths): the picture for each size in both looks, the preview and metadata."""
    files = ["metadata.json", "contents/screenshot.png"]
    for folder in ("images", "images_dark"):
        files += [f"contents/{folder}/{w}x{h}.png" for w, h in SIZES]
    return files


def _data_uri(svg):
    return "data:image/svg+xml;base64," + base64.b64encode(svg.encode("ascii")).decode()


SHEET_W, SHEET_H = 1920, 1560


def build_sheet():
    """The review sheet: light and dark 16:9, then an ultrawide, a 16:10 and a portrait screen."""
    W, H = SHEET_W, SHEET_H
    parts = [f'<rect width="{W}" height="{H}" fill="#1b2330"/>']

    def tile(mode, w, h, x, yy, width, label):
        height = width * h / w
        parts.append(f'<image href="{_data_uri(scene(w, h, mode))}" x="{x}" y="{yy}" width="{width}" height="{height:.0f}"/>')
        parts.append(f'<rect x="{x - 1}" y="{yy - 1}" width="{width + 2}" height="{height + 2:.0f}" fill="none" stroke="#7a8699" stroke-width="2"/>')
        parts.append(f'<text x="{x}" y="{yy - 10}" font-family="Nunito, sans-serif" font-size="24" fill="#aab1bd">{label}</text>')
        return height

    tile("light", 1920, 1080, 40, 50, 880, "light 16:9")
    tile("dark", 1920, 1080, 960, 50, 880, "dark 16:9")
    tile("dark", 3440, 1440, 40, 640, 880, "dark ultrawide 21:9")
    tile("light", 2560, 1600, 960, 640, 560, "light 16:10")
    tile("dark", 1080, 1920, 1560, 640, 280, "dark portrait")
    tile("light", 2736, 1824, 40, 1110, 540, "light 3:2 (Surface)")
    tile("dark", 1024, 768, 620, 1110, 460, "dark 4:3")
    body = "".join(parts)
    return (HEADER + f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" role="img" '
            f'aria-label="nisse wallpaper review sheet">' + LF + '  <title>nisse wallpaper review sheet</title>' + LF + f'  {body}' + LF + '</svg>' + LF)


def _screenshot(page, svg, w, h):
    uri = _data_uri(svg)
    page.set_viewport_size({"width": w, "height": h})
    page.set_content(f'<html><body style="margin:0"><img src="{uri}" width="{w}" height="{h}" style="display:block"></body></html>')
    page.wait_for_function("document.images[0].complete")
    return page.screenshot(clip={"x": 0, "y": 0, "width": w, "height": h})


def main(argv=None):
    from playwright.sync_api import sync_playwright
    argv = sys.argv[1:] if argv is None else argv
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "svg").mkdir(exist_ok=True)
    for mode in MODES:
        (OUT / "svg" / f"nisse-wallpaper-{mode}-1920x1080.svg").write_text(scene(1920, 1080, mode), encoding="ascii", newline=LF)
    sheet, w, h = build_sheet(), SHEET_W, SHEET_H
    (OUT / "sheet.svg").write_text(sheet, encoding="ascii", newline=LF)
    with sync_playwright() as p:
        browser = p.chromium.launch()
        page = browser.new_page()
        (OUT / "sheet.png").write_bytes(_screenshot(page, sheet, w, h))
        if "--all" in argv:
            pkg = ROOT / "out" / "wallpapers" / "nisse"
            (pkg / "contents").mkdir(parents=True, exist_ok=True)
            (pkg / "metadata.json").write_text(metadata(), encoding="ascii", newline=LF)
            for folder, mode in (("images", "light"), ("images_dark", "dark")):
                (pkg / "contents" / folder).mkdir(parents=True, exist_ok=True)
                for sw, sh in SIZES:
                    (pkg / "contents" / folder / f"{sw}x{sh}.png").write_bytes(_screenshot(page, scene(sw, sh, mode), sw, sh))
            (pkg / "contents" / "screenshot.png").write_bytes(_screenshot(page, scene(600, 338, "dark"), 600, 338))
            print(f"wrote the Plasma wallpaper folder to {pkg}")
        browser.close()
    print(f"wrote the review sheet and the 16:9 masters to {OUT}")


if __name__ == "__main__":
    sys.exit(main())
