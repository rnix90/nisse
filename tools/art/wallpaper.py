"""N-407: the nisse wallpaper: three base concepts from an independent art director's brief.

Bert's direction (2026-11-16): "simpler, more geometric, no house, like XP's Bliss if it was in the world of Tron doing a
simulation of Scandinavia". Two rounds (a cottage scene, then a gridded hill with outlined firs) were too busy and had the wrong
Scandinavian cues, so an independent art director was shown the good nisse art and wrote a tighter brief. Its rules, enforced by
tests/test_wallpaper.py:

  - solid fills with no outlines (only thin lines are stroked), flat shapes, no gradients, no clouds, no snow caps, no outlined firs;
  - at most six Ember palette colors in a look, fewer than 25 marks in a picture;
  - exactly one orange (the sun and what belongs to it) and so one focal point; the sun stays out of the left fifth (desktop icons);
  - true Scandinavian landforms: rounded, flat-topped fjell and steep fjord walls, not sharp Alpine peaks;
  - Bliss is the scale (one huge simple landform, an enormous calm sky); Tron is one flat plane of thin receding lines and one glow line.

Three different concepts: "fjord-gate" (a gridded fjord between two steep walls to a low sun), "one-hill" (one huge smooth hill, the
logo's horizon curve, with a single light-cycle trail) and "fjell-layers" (four stacked flat-topped ridges and a fjord arm).
Light and dark are the SAME scene with only the colors changed. The picture is made of fractions of the screen size, so every screen
shape gets the whole scene; on ultrawide and portrait screens the focal point is pulled toward the middle.
Plasma wants `contents/images/WIDTHxHEIGHT.png` and `contents/images_dark/WIDTHxHEIGHT.png` (verified in the image, see
`package_files()`).

    python tools/art/wallpaper.py                       writes the review sheet and the 16:9 masters to assets/art/wallpaper/
    python tools/art/wallpaper.py --all [--concept NAME] [--out DIR]
                                                        also renders the whole Plasma wallpaper folder (the chosen concept unless
                                                        told otherwise) to DIR (default out/wallpapers/nisse/; the committed copy the
                                                        nisse-wallpaper package installs is assets/art/wallpaper/package/nisse)
"""
