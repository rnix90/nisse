class Rng:
    """A tiny deterministic random source, so the same screen shape always gives the same picture."""

    def __init__(self, seed):
        self.state = seed

    def next(self):
        self.state = (self.state * 1103515245 + 12345) % 2147483648
        return self.state / 2147483648

    def between(self, lo, hi):
        return lo + (hi - lo) * self.next()


def f1(v):
    return f"{v:.1f}"


def pts(points):
    return " ".join(f"{f1(x)},{f1(y)}" for x, y in points)


def pull(v, w, h):
    """A design fraction of the width, pulled toward the middle on screens much wider or taller than 16:9."""
    ratio = w / h
    k = min(ratio / (16 / 9), (16 / 9) / ratio)
    return w * (0.5 + (v - 0.5) * k)


def rounded(vertices, r):
    """A closed path through the vertices with each corner rounded by radius r (a quadratic curve), as one flat shape."""
    n = len(vertices)
    out = []
    for i in range(n):
        p0, p1, p2 = vertices[i - 1], vertices[i], vertices[(i + 1) % n]
        a, b = math.dist(p0, p1), math.dist(p1, p2)
        ra, rb = min(r, a / 2), min(r, b / 2)
        s = (p1[0] + (p0[0] - p1[0]) * ra / a, p1[1] + (p0[1] - p1[1]) * ra / a)
        e = (p1[0] + (p2[0] - p1[0]) * rb / b, p1[1] + (p2[1] - p1[1]) * rb / b)
        out.append(("M" if i == 0 else "L") + f"{f1(s[0])} {f1(s[1])} Q{f1(p1[0])} {f1(p1[1])} {f1(e[0])} {f1(e[1])}")
    return " ".join(out) + " Z"


def ridge(rng, w, h, top, wobble, widths, corner, lean):
    """A fjell ridge: a staircase of flat plateaus with steep, slightly leaning sides and rounded shoulders, filled to the bottom."""
    x = -0.06 * w
    yt = (top + rng.between(-wobble, wobble)) * h
    verts = [(x, h * 1.02), (x, yt)]
    while x < 1.06 * w:
        x += rng.between(*widths) * w
        verts.append((x, yt))
        yt = (top + rng.between(-wobble, wobble)) * h
        verts.append((x + lean * w, yt))
    verts += [(x + lean * w, h * 1.02)]
    return rounded(verts, corner * h)


def line(x1, y1, x2, y2, width, color, extra=""):
    return (f'<line{extra} x1="{f1(x1)}" y1="{f1(y1)}" x2="{f1(x2)}" y2="{f1(y2)}" stroke="{color}" stroke-width="{f1(width)}" '
            f'stroke-linecap="round"/>')


def sun(cx, cy, r, color):
    return f'<circle id="sun" cx="{f1(cx)}" cy="{f1(cy)}" r="{f1(r)}" fill="{color}"/>'


def fjord_gate(w, h, p):
    """A gridded fjord running between two steep, unequal fjell walls to a low sun in the gap (Tron-forward, Monument-Valley calm).

    Round 2 (art director): the walls are unequal (the left wider and lower, the right narrower and taller), have rounded plateau
    corners, near-vertical inner faces and a long concave slope down to the screen edge; the grid is brighter near the viewer; the
    reflection is three stacked dashes."""
    u = h / 900
    hy = 0.58 * h
    sx = pull(0.54, w, h)
    r = min(0.09 * h, 0.11 * w)
    tl, tr = hy - 0.22 * h, hy - 0.36 * h
    cr = 0.03 * h
    wall_l = (f"M{f1(-0.05 * w)} {f1(hy)} C{f1(0.10 * w)} {f1(hy)} {f1(0.15 * w)} {f1(tl)} {f1(0.25 * w)} {f1(tl)} H{f1(0.40 * w - 2 * cr)} "
              f"Q{f1(0.40 * w)} {f1(tl)} {f1(0.40 * w)} {f1(tl + cr * 1.6)} L{f1(0.405 * w)} {f1(hy)} Z")
    wall_r = (f"M{f1(1.05 * w)} {f1(hy)} C{f1(0.92 * w)} {f1(hy)} {f1(0.88 * w)} {f1(tr)} {f1(0.80 * w)} {f1(tr)} H{f1(0.66 * w + 2 * cr)} "
              f"Q{f1(0.66 * w)} {f1(tr)} {f1(0.66 * w)} {f1(tr + cr * 1.6)} L{f1(0.655 * w)} {f1(hy)} Z")
    radials = "".join(line(sx, hy, sx + (k - 3.5) * 0.22 * w, h, 2 * u, p["grid-near"] if k in (0, 1, 6, 7) else p["grid"]) for k in range(8))
    horizontals = "".join(line(0, hy + (h - hy) * ((i + 0.7) / 6) ** 1.8, w, hy + (h - hy) * ((i + 0.7) / 6) ** 1.8, 2 * u,
                               p["grid-near"] if i >= 4 else p["grid"]) for i in range(6))
    dashes = "".join(f'<rect x="{f1(sx - dw * u / 2)}" y="{f1(hy + 0.035 * h + i * 20 * u)}" width="{f1(dw * u)}" height="{f1(6 * u)}" '
                     f'rx="{f1(3 * u)}" fill="{p["orange"]}"/>' for i, dw in enumerate((100, 60, 30)))
    return (f'<rect id="sky" width="{w}" height="{h}" fill="{p["sky"]}"/>'
            + sun(sx, hy, r, p["orange"])
            + f'<path id="wall-left" d="{wall_l}" fill="{p["wall-left"]}"/><path id="wall-right" d="{wall_r}" fill="{p["wall-right"]}"/>'
            + f'<rect id="water" x="0" y="{f1(hy)}" width="{w}" height="{f1(h - hy)}" fill="{p["water"]}"/>'
            + f'<g id="grid">{radials}{horizontals}</g>'
            + line(0.405 * w, hy, 0.655 * w, hy, 3.5 * u, p["orange"], ' id="glow"')
            + f'<g id="reflection">{dashes}</g>')


def cubic(p0, p1, p2, p3, t):
    mt = 1 - t
    return (mt ** 3 * p0[0] + 3 * mt * mt * t * p1[0] + 3 * mt * t * t * p2[0] + t ** 3 * p3[0],
            mt ** 3 * p0[1] + 3 * mt * mt * t * p1[1] + 3 * mt * t * t * p2[1] + t ** 3 * p3[1])


def one_hill(w, h, p):
    """One huge smooth hill (the logo's horizon curve) under a big sky; a far fjell plateau with the sun sunk into its top edge
    (the midnight-sun cue); one tapered light-cycle trail that ends under the sun's column. (Rounds 2 and 3, art director.)"""
    u = h / 900
    sx = pull(0.62, w, h)
    top, r = 0.37 * h, 0.06 * h
    sun_y = top + 0.12 * r                      # the center sits just below the plateau's top edge: a true half disc sunk in it
    # the plateau: a low ramp on the left, a left shoulder, a flat top, a steep right-hand cliff down to a notch, a lower shoulder
    plateau = rounded([(-0.06 * w, h * 1.02), (-0.06 * w, 0.52 * h), (sx - 0.30 * w, 0.52 * h), (sx - 0.10 * w, top),
                       (sx + 0.24 * w, top), (sx + 0.27 * w, 0.54 * h), (sx + 0.34 * w, 0.54 * h), (sx + 0.37 * w, 0.49 * h),
                       (1.06 * w, 0.49 * h), (1.06 * w, h * 1.02)], 0.03 * h)
    crest_x, crest_y = 0.38 * w, 0.45 * h
    right = ((crest_x, crest_y), (0.62 * w, crest_y), (0.82 * w, 0.62 * h), (w, 0.70 * h))
    hill = (f"M0 {f1(0.64 * h)} C{f1(0.16 * w)} {f1(0.50 * h)} {f1(0.26 * w)} {f1(crest_y)} {f1(crest_x)} {f1(crest_y)} "
            f"C{f1(right[1][0])} {f1(right[1][1])} {f1(right[2][0])} {f1(right[2][1])} {f1(right[3][0])} {f1(right[3][1])} V{h} H0 Z")
    # where the hill's top edge is under the sun's column
    lo, hi = 0.0, 1.0
    for _ in range(40):
        mid = (lo + hi) / 2
        if cubic(*right, mid)[0] < sx:
            lo = mid
        else:
            hi = mid
    end = cubic(*right, (lo + hi) / 2)
    # the trail: a tapered ribbon, 5 units wide at the bottom edge and 2 at the hill's edge, near the glow weight, aimed at the sun's column
    p0, p1, p2, p3 = (sx - 0.10 * w, 1.02 * h), (sx - 0.12 * w, 0.84 * h), (sx - 0.04 * w, 0.66 * h), (end[0], end[1] + 0.004 * h)
    left, rgt = [], []
    for k in range(41):
        t = k / 40
        x, y = cubic(p0, p1, p2, p3, t)
        x2, y2 = cubic(p0, p1, p2, p3, min(1.0, t + 0.01))
        x1, y1 = cubic(p0, p1, p2, p3, max(0.0, t - 0.01))
        dx, dy = x2 - x1, y2 - y1
        n = math.hypot(dx, dy) or 1
        hw = (1.5 * (1 - t) + 1.0) * u
        left.append((x - dy / n * hw, y + dx / n * hw))
        rgt.append((x + dy / n * hw, y - dx / n * hw))
    ribbon = left + rgt[::-1]
    return (f'<rect id="sky" width="{w}" height="{h}" fill="{p["sky"]}"/>'
            + sun(sx, sun_y, r, p["orange"])
            + f'<path id="plateau" d="{plateau}" fill="{p["fjell"]}"/><path id="hill" d="{hill}" fill="{p["hill"]}"/>'
            + f'<polygon id="trail" points="{pts(ribbon)}" fill="{p["orange"]}"/>')


def fjell_layers(w, h, p):
    """Two receding fjell ridges, a fjord of open dark water with perspective scan lines, and one headland in front, shaped by hand:
    a far plateau on the right whose steep wall drops toward the sun, a near-left mass with its own diagonal into the fjord, the sun
    sunk in the gap between them. (Rounds 2 and 3, art director: the stepped lower layers are gone; one asymmetric headland rises
    diagonally from the water. The owner then chose this concept and asked for the horizontal orange glow line to go: the sun is
    the only orange.)"""
    u = h / 900
    sx = pull(0.34, w, h)
    rs = 0.07 * h
    gl = max(0.10 * w, 1.7 * rs)       # how far the far wall stands from the sun: wider on a narrow screen so the sun is never clipped
    g2 = max(0.05 * w, 1.3 * rs)
    r1 = rounded([(-0.06 * w, h * 1.02), (-0.06 * w, 0.60 * h), (sx + gl, 0.60 * h), (sx + gl + 0.13 * w, 0.38 * h),
                  (1.06 * w, 0.38 * h), (1.06 * w, h * 1.02)], 0.03 * h)
    r2 = rounded([(-0.06 * w, h * 1.02), (-0.06 * w, 0.48 * h), (sx - g2 - 0.09 * w, 0.48 * h), (sx - g2, 0.585 * h),
                  (sx + g2 + 0.10 * w, 0.585 * h), (sx + g2 + 0.17 * w, 0.55 * h), (sx + g2 + 0.42 * w, 0.55 * h),
                  (sx + g2 + 0.46 * w, 0.60 * h), (1.06 * w, 0.60 * h), (1.06 * w, h * 1.02)], 0.03 * h)
    water_top = 0.585 * h
    scans = "".join(line(0, y * h, w, y * h, 2 * u, p["scan"], ' class="scan"') for y in (0.625, 0.685, 0.765, 0.87))
    headland = rounded([(0.05 * w, h * 1.02), (0.16 * w, 0.93 * h), (0.24 * w, 0.79 * h), (0.66 * w, 0.64 * h), (0.80 * w, 0.65 * h),
                        (1.06 * w, 0.73 * h), (1.06 * w, h * 1.02)], 0.04 * h)
    return (f'<rect id="sky" width="{w}" height="{h}" fill="{p["sky"]}"/>'
            + f'<path id="ridge-1" d="{r1}" fill="{p["r1"]}"/>'
            + sun(sx, 0.575 * h, rs, p["orange"])
            + f'<path id="ridge-2" d="{r2}" fill="{p["r2"]}"/>'
            + f'<rect id="water" x="0" y="{f1(water_top)}" width="{w}" height="{f1(h - water_top + 2)}" fill="{p["water"]}"/>{scans}'
            + f'<path id="headland" d="{headland}" fill="{p["headland"]}"/>')


CONCEPTS = {"fjord-gate": fjord_gate, "one-hill": one_hill, "fjell-layers": fjell_layers}


def scene(w, h, mode, concept="fjell-layers"):
    """The whole picture for a screen of w x h pixels in the "dark" or "light" look (an SVG document)."""
    pal = PALETTES[concept][mode]
    hd = min(h, 1.45 * w)        # on a portrait screen the scene sits on a shorter canvas at the bottom, under extra sky
    body = CONCEPTS[concept](w, hd, pal)
    if hd < h:
        body = f'<rect id="sky-top" width="{w}" height="{h}" fill="{pal["sky"]}"/><g transform="translate(0 {f1(h - hd)})">{body}</g>'
    label = f"nisse wallpaper, {concept}, {mode}, {w} by {h}"
    return (HEADER + f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}" role="img" '
            f'aria-label="{label}">' + LF + f'  <title>{label}</title>' + LF + f'  {body}' + LF + '</svg>' + LF)


def metadata():
    meta = {"KPlugin": {"Authors": [{"Name": "nisse"}], "Id": "nisse", "Name": "nisse", "License": "GPL-2.0-or-later",
                        "Description": "A quiet Scandinavian evening, a simulation, in a light and a dark look."}}
    return json.dumps(meta, indent=4) + LF


def package_files():
    """Every file of the Plasma wallpaper folder (relative paths): the picture for each size in both looks, the preview and metadata."""
    files = ["metadata.json", "contents/screenshot.png"]
    for folder in ("images", "images_dark"):
        files += [f"contents/{folder}/{w}x{h}.png" for w, h in SIZES]
    return files


def _data_uri(svg):
    return "data:image/svg+xml;base64," + base64.b64encode(svg.encode("ascii")).decode()


SHEET_W, SHEET_H = 1920, 1230


def build_sheet():
    """The review sheet: each concept in a row, dark and light 16:9, then an ultrawide and a portrait screen."""
    W, H = SHEET_W, SHEET_H
    parts = [f'<rect width="{W}" height="{H}" fill="#1b2330"/>']

    def tile(concept, mode, w, h, x, y, width, label):
        height = width * h / w
        parts.append(f'<image href="{_data_uri(scene(w, h, mode, concept))}" x="{x}" y="{y}" width="{width}" height="{height:.0f}"/>')
        parts.append(f'<rect x="{x - 1}" y="{y - 1}" width="{width + 2}" height="{height + 2:.0f}" fill="none" stroke="#7a8699" stroke-width="2"/>')
        parts.append(f'<text x="{x}" y="{y - 8}" font-family="Nunito, sans-serif" font-size="20" fill="#aab1bd">{label}</text>')

    for row, concept in enumerate(CONCEPTS):
        y = 50 + row * 395
        parts.append(f'<text x="40" y="{y - 26}" font-family="Nunito, sans-serif" font-size="30" fill="#f6f2e9">{row + 1}. {concept}</text>')
        tile(concept, "dark", 1920, 1080, 40, y, 560, "dark 16:9")
        tile(concept, "light", 1920, 1080, 640, y, 560, "light 16:9")
        tile(concept, "dark", 3440, 1440, 1240, y, 440, "dark ultrawide 21:9")
        tile(concept, "dark", 1080, 1920, 1720, y, 168, "portrait")
    body = "".join(parts)
    return (HEADER + f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" role="img" '
            f'aria-label="nisse wallpaper review sheet">' + LF + '  <title>nisse wallpaper review sheet</title>' + LF + f'  {body}' + LF + '</svg>' + LF)


def _screenshot(page, svg, w, h):
    uri = _data_uri(svg)
    page.set_viewport_size({"width": w, "height": h})
    page.set_content(f'<html><body style="margin:0"><img src="{uri}" width="{w}" height="{h}" style="display:block"></body></html>')
    page.wait_for_function("document.images[0].complete")
    return page.screenshot(clip={"x": 0, "y": 0, "width": w, "height": h})


def main(argv=None):
    from playwright.sync_api import sync_playwright
    argv = sys.argv[1:] if argv is None else argv
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "svg").mkdir(exist_ok=True)
    for concept in CONCEPTS:
        for mode in MODES:
            (OUT / "svg" / f"nisse-wallpaper-{concept}-{mode}-1920x1080.svg").write_text(scene(1920, 1080, mode, concept), encoding="ascii", newline=LF)
    sheet = build_sheet()
    (OUT / "sheet.svg").write_text(sheet, encoding="ascii", newline=LF)
    with sync_playwright() as p:
        browser = p.chromium.launch()
        page = browser.new_page()
        (OUT / "sheet.png").write_bytes(_screenshot(page, sheet, SHEET_W, SHEET_H))
        if "--all" in argv:
            concept = argv[argv.index("--concept") + 1] if "--concept" in argv else CHOSEN
            pkg = Path(argv[argv.index("--out") + 1]) if "--out" in argv else ROOT / "out" / "wallpapers" / "nisse"
            (pkg / "contents").mkdir(parents=True, exist_ok=True)
            (pkg / "metadata.json").write_text(metadata(), encoding="ascii", newline=LF)
            for folder, mode in (("images", "light"), ("images_dark", "dark")):
                (pkg / "contents" / folder).mkdir(parents=True, exist_ok=True)
                for sw, sh in SIZES:
                    (pkg / "contents" / folder / f"{sw}x{sh}.png").write_bytes(_screenshot(page, scene(sw, sh, mode, concept), sw, sh))
            (pkg / "contents" / "screenshot.png").write_bytes(_screenshot(page, scene(600, 338, "dark", concept), 600, 338))
            print(f"wrote the Plasma wallpaper folder ({concept}) to {pkg}")
        browser.close()
    print(f"wrote the review sheet and the 16:9 masters to {OUT}")


if __name__ == "__main__":
    sys.exit(main())
