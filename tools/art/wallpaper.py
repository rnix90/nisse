"""N-407: the nisse wallpaper: Windows XP's Bliss in the world of Tron, a simulation of Scandinavia.

Bert's direction (2026-11-16): simpler, more geometric, no house. One big rolling hill (the logo's horizon curve) fills the lower
third like Bliss, with a glowing grid laid over it like Tron's floor; behind it a fjord with scan lines, wireframe low-poly
mountains with snow caps, geometric firs standing on the hill, and a sun drawn as a disc inside rings. Everything is a flat
shape or a thin line from the Ember palette. Light and dark are the SAME scene with only the colors changed.

The picture is drawn in units of 1/900 of the screen height (or 1/1200 of the width on a portrait screen), anchored to the bottom,
so every shape of screen gets the same scene: a wider screen shows more land (more peaks and firs), not a stretched picture.
Plasma wants a folder `contents/images/WIDTHxHEIGHT.png` and `contents/images_dark/WIDTHxHEIGHT.png` (verified in the image:
Fedora's Next wallpaper has exactly that); `package_files()` lists it.

    python tools/art/wallpaper.py           writes the review sheet and the 16:9 masters to assets/art/wallpaper/
    python tools/art/wallpaper.py --all     also renders the whole Plasma wallpaper folder to out/wallpapers/nisse/
"""
import base64
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "assets" / "art" / "wallpaper"
LF = chr(10)
COLOR_BUDGET = 16

HEADER = ('<?xml version="1.0" encoding="UTF-8"?>' + LF + '<!-- SPDX-License-Identifier: GPL-2.0-or-later -->' + LF
          + '<!-- Generated by tools/art/wallpaper.py (N-407). Ember palette only, flat shapes and thin lines. -->' + LF)

# the screen shapes Plasma should find a picture for (16:9, 16:10, 21:9, 4:3, 3:2 Surface, portrait)
SIZES = [(1280, 720), (1920, 1080), (2560, 1440), (3840, 2160), (5120, 2880),
         (1280, 800), (1920, 1200), (2560, 1600), (3840, 2400),
         (2560, 1080), (3440, 1440), (5120, 2160),
         (1024, 768), (2048, 1536), (2736, 1824), (1080, 1920), (1440, 2960)]

# roles -> Ember palette hex. The same roles in both looks.
DARK = {
    "sky": "#1b2330", "ring": "#354156", "sun": "#e0623f", "cloud": "#222c3b",
    "far-fill": "#222c3b", "far-line": "#7a8699", "mid-fill": "#2b3749", "mid-line": "#aab1bd", "snow": "#aab1bd",
    "water": "#222c3b", "scan": "#354156", "reflection": "#e0623f",
    "hill": "#2b3749", "grid": "#7a8699", "grid-bright": "#bd573c", "rim": "#f28463",
    "fir-fill": "#1b2330", "fir-line": "#e0623f",
}
LIGHT = {
    "sky": "#fffdf8", "ring": "#f6f2e9", "sun": "#e0623f", "cloud": "#f6f2e9",
    "far-fill": "#f6f2e9", "far-line": "#aab1bd", "mid-fill": "#aab1bd", "mid-line": "#7a8699", "snow": "#fffdf8",
    "water": "#f6f2e9", "scan": "#aab1bd", "reflection": "#e0623f",
    "hill": "#f6f2e9", "grid": "#aab1bd", "grid-bright": "#bd4525", "rim": "#bd4525",
    "fir-fill": "#fffdf8", "fir-line": "#1b2330",
}
MODES = {"dark": DARK, "light": LIGHT}

HILL_PEAK = 430      # the hill's highest point above the bottom edge, in units of 1/900 of the height
SHORE = 300          # where the mountains and the fjord meet, above the bottom edge


def horizon_px(height):
    """How high the top of the hill is above the bottom edge, in pixels, on a screen of this height."""
    return HILL_PEAK * height / 900


class Rng:
    """A tiny deterministic random source, so the same screen shape always gives the same picture."""

    def __init__(self, seed):
        self.state = seed

    def next(self):
        self.state = (self.state * 1103515245 + 12345) % 2147483648
        return self.state / 2147483648

    def between(self, lo, hi):
        return lo + (hi - lo) * self.next()


def f1(v):
    return f"{v:.1f}"


def pts(points):
    return " ".join(f"{f1(x)},{f1(y)}" for x, y in points)


def fir(x, base, h):
    """The outline points of a tiered fir (one flat polygon)."""
    w = 0.5 * h
    return [(x, base - h), (x + 0.22 * w, base - 0.62 * h), (x + 0.12 * w, base - 0.62 * h), (x + 0.34 * w, base - 0.34 * h),
            (x + 0.2 * w, base - 0.34 * h), (x + 0.5 * w, base), (x - 0.5 * w, base), (x - 0.2 * w, base - 0.34 * h),
            (x - 0.34 * w, base - 0.34 * h), (x - 0.12 * w, base - 0.62 * h), (x - 0.22 * w, base - 0.62 * h)]


def lerp(a, b, t):
    return (a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t)


def mountains(rng, wu, base, hmin, hmax, fill, line, snow_color, snow, spacing):
    """A band of low-poly peaks across the width: one outlined polygon, plus a snow cap on each peak when `snow`."""
    peaks, x = [], -spacing * rng.between(0.2, 0.9)
    while x < wu + spacing:
        peaks.append((x, base - rng.between(hmin, hmax)))
        x += spacing * rng.between(0.8, 1.25)
    ridge = [(peaks[0][0] - spacing * 0.6, base)]
    valleys = []
    for i, p in enumerate(peaks):
        if i:
            q = peaks[i - 1]
            v = ((p[0] + q[0]) / 2, base - rng.between(0.1, 0.32) * min(base - p[1], base - q[1]))
            valleys.append(v)
            ridge.append(v)
        ridge.append(p)
    ridge.append((peaks[-1][0] + spacing * 0.6, base))
    out = [f'<polygon points="{pts(ridge)}" fill="{fill}" stroke="{line}" stroke-width="3" stroke-linejoin="round"/>']
    if snow:
        for i, p in enumerate(peaks):
            left = valleys[i - 1] if i else (p[0] - spacing * 0.6, base)
            right = valleys[i] if i < len(valleys) else (p[0] + spacing * 0.6, base)
            lp, rp = lerp(p, left, 0.34), lerp(p, right, 0.34)
            d = max(lp[1], rp[1]) - p[1]
            cap = [p, rp, (p[0] + (rp[0] - p[0]) * 0.45, rp[1] - 0.12 * d), (p[0] + (rp[0] - p[0]) * 0.1, rp[1] + 0.05 * d),
                   (p[0] - (p[0] - lp[0]) * 0.4, lp[1] - 0.10 * d), lp]
            out.append(f'<polygon points="{pts(cap)}" fill="{snow_color}"/>')
    return "".join(out)


def hill_height(x, cx):
    """The hill's height above the bottom edge at x: a smooth Bliss dome left of centre, falling away to the right."""
    return 150 + (HILL_PEAK - 150) * math.exp(-(((x - (cx - 180)) / 560) ** 2)) + 60 * math.exp(-(((x - (cx + 480)) / 320) ** 2))


def scene(w, h, mode):
    """The whole picture for a screen of w x h pixels in the "dark" or "light" look (an SVG document)."""
    pal = MODES[mode]
    s = min(h / 900, w / 1200)
    wu, hu = w / s, h / s
    cx = wu / 2

    def y(offset):               # a height above the bottom edge, in units
        return hu - offset

    rng = Rng(w * 31 + h * 17)
    sun_x, sun_y = cx + 280, y(640)
    sun = (f'<g id="sun"><circle cx="{f1(sun_x)}" cy="{f1(sun_y)}" r="190" fill="none" stroke="{pal["ring"]}" stroke-width="3"/>'
           f'<circle cx="{f1(sun_x)}" cy="{f1(sun_y)}" r="130" fill="none" stroke="{pal["ring"]}" stroke-width="3"/>'
           f'<circle cx="{f1(sun_x)}" cy="{f1(sun_y)}" r="72" fill="{pal["sun"]}"/></g>')
    clouds = []
    for ccx, coff, cw in ((cx - 430, 760, 250), (cx - 40, 840, 200), (cx + 520, 760, 280), (cx - 760, 650, 160), (cx + 860, 840, 190)):
        for k, (dx, ww) in enumerate(((0, cw), (cw * 0.18, cw * 0.7), (-cw * 0.1, cw * 0.55))):
            clouds.append(f'<rect x="{f1(ccx + dx - ww / 2)}" y="{f1(y(coff) + k * 17)}" width="{f1(ww)}" height="14" rx="7" fill="{pal["cloud"]}"/>')
    clouds = f'<g id="clouds">{"".join(clouds)}</g>'
    far = f'<g id="mountains-far">{mountains(rng, wu, y(SHORE), 130, 250, pal["far-fill"], pal["far-line"], pal["snow"], True, 330)}</g>'
    mid = f'<g id="mountains-mid">{mountains(rng, wu, y(SHORE - 6), 60, 140, pal["mid-fill"], pal["mid-line"], pal["snow"], False, 250)}</g>'
    water_top, water_bottom = y(SHORE - 6), y(100)
    scans = "".join(f'<line x1="0" y1="{f1(water_top + 18 + k * 16)}" x2="{f1(wu)}" y2="{f1(water_top + 18 + k * 16)}" stroke="{pal["scan"]}" stroke-width="2"/>'
                    for k in range(int((water_bottom - water_top) / 16)))
    reflection = "".join(f'<rect x="{f1(sun_x - rw / 2)}" y="{f1(water_top + 22 + i * 32)}" width="{rw}" height="8" rx="4" fill="{pal["reflection"]}"/>'
                         for i, rw in enumerate((140, 100, 66, 36)))
    water = (f'<g id="water"><rect x="0" y="{f1(water_top)}" width="{f1(wu)}" height="{f1(water_bottom - water_top + 2)}" fill="{pal["water"]}"/>'
             f'{scans}{reflection}</g>')
    xs = [i * 16 - 16 for i in range(int(wu / 16) + 4)]
    curve = [(xx, y(hill_height(xx, cx))) for xx in xs]
    top = "M" + " L".join(f"{f1(a)} {f1(b)}" for a, b in curve)
    hill_d = top + f" L{f1(xs[-1])} {f1(hu)} L{f1(xs[0])} {f1(hu)} Z"
    clip = f'<clipPath id="hill-clip"><path d="{hill_d}"/></clipPath>'
    hill = f'<path id="hill" d="{hill_d}" fill="{pal["hill"]}"/>'
    contours = "".join(f'<path d="M{" L".join(f"{f1(a)} {f1(b + dd)}" for a, b in curve)}" fill="none" stroke="{pal["grid"]}" stroke-width="1.8"/>'
                       for dd in (16, 36, 62, 96, 140, 196, 264, 346, 444))
    vx = cx + 60
    radials = "".join(
        f'<line x1="{f1(xx)}" y1="{f1(y(hill_height(xx, cx)))}" x2="{f1(vx + (xx - vx) * 3.4)}" y2="{f1(hu)}" '
        f'stroke="{pal["grid-bright"] if k % 4 == 0 else pal["grid"]}" stroke-width="1.8"/>'
        for k, xx in enumerate(range(int(-wu * 0.7), int(wu * 1.7), 64)))
    grid = f'<g id="grid" clip-path="url(#hill-clip)">{contours}{radials}</g>'
    rim = f'<path id="rim" d="{top}" fill="none" stroke="{pal["rim"]}" stroke-width="4" stroke-linejoin="round"/>'
    trees = []
    count = max(8, int(wu / 130))
    for k in range(count):                                   # evenly spread with a jitter, so the firs do not pile up
        tx = (k + rng.between(0.15, 0.85)) * wu / count
        depth = rng.between(26, 280)
        base = y(hill_height(tx, cx)) + depth
        trees.append((base, fir(tx, base, 46 + depth * 0.42)))
    firs = "".join(f'<polygon points="{pts(p)}"/>' for _, p in sorted(trees, key=lambda t: t[0]))
    firs = f'<g id="firs" fill="{pal["fir-fill"]}" stroke="{pal["fir-line"]}" stroke-width="3" stroke-linejoin="round">{firs}</g>'
    body = (f'<g transform="scale({s:.5f})"><defs>{clip}</defs><rect id="sky" width="{f1(wu)}" height="{f1(hu)}" fill="{pal["sky"]}"/>'
            f'{clouds}{sun}{far}{mid}{water}{hill}{grid}{rim}{firs}</g>')
    label = f"nisse wallpaper, {mode}, {w} by {h}"
    return (HEADER + f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}" role="img" '
            f'aria-label="{label}">' + LF + f'  <title>{label}</title>' + LF + f'  {body}' + LF + '</svg>' + LF)


def metadata():
    meta = {"KPlugin": {"Authors": [{"Name": "nisse"}], "Id": "nisse", "Name": "nisse", "License": "GPL-2.0-or-later",
                        "Description": "A rolling hill with a grid under a ring sun, a simulation of Scandinavia, in a light and a dark look"}}
    return json.dumps(meta, indent=4) + LF


def package_files():
    """Every file of the Plasma wallpaper folder (relative paths): the picture for each size in both looks, the preview and metadata."""
    files = ["metadata.json", "contents/screenshot.png"]
    for folder in ("images", "images_dark"):
        files += [f"contents/{folder}/{w}x{h}.png" for w, h in SIZES]
    return files


def _data_uri(svg):
    return "data:image/svg+xml;base64," + base64.b64encode(svg.encode("ascii")).decode()


SHEET_W, SHEET_H = 1920, 1560


def build_sheet():
    """The review sheet: light and dark 16:9, then an ultrawide, a 16:10 and a portrait screen."""
    W, H = SHEET_W, SHEET_H
    parts = [f'<rect width="{W}" height="{H}" fill="#1b2330"/>']

    def tile(mode, w, h, x, yy, width, label):
        height = width * h / w
        parts.append(f'<image href="{_data_uri(scene(w, h, mode))}" x="{x}" y="{yy}" width="{width}" height="{height:.0f}"/>')
        parts.append(f'<rect x="{x - 1}" y="{yy - 1}" width="{width + 2}" height="{height + 2:.0f}" fill="none" stroke="#7a8699" stroke-width="2"/>')
        parts.append(f'<text x="{x}" y="{yy - 10}" font-family="Nunito, sans-serif" font-size="24" fill="#aab1bd">{label}</text>')
        return height

    tile("light", 1920, 1080, 40, 50, 880, "light 16:9")
    tile("dark", 1920, 1080, 960, 50, 880, "dark 16:9")
    tile("dark", 3440, 1440, 40, 640, 880, "dark ultrawide 21:9")
    tile("light", 2560, 1600, 960, 640, 560, "light 16:10")
    tile("dark", 1080, 1920, 1560, 640, 280, "dark portrait")
    tile("light", 2736, 1824, 40, 1110, 540, "light 3:2 (Surface)")
    tile("dark", 1024, 768, 620, 1110, 460, "dark 4:3")
    body = "".join(parts)
    return (HEADER + f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" role="img" '
            f'aria-label="nisse wallpaper review sheet">' + LF + '  <title>nisse wallpaper review sheet</title>' + LF + f'  {body}' + LF + '</svg>' + LF)


def _screenshot(page, svg, w, h):
    uri = _data_uri(svg)
    page.set_viewport_size({"width": w, "height": h})
    page.set_content(f'<html><body style="margin:0"><img src="{uri}" width="{w}" height="{h}" style="display:block"></body></html>')
    page.wait_for_function("document.images[0].complete")
    return page.screenshot(clip={"x": 0, "y": 0, "width": w, "height": h})


def main(argv=None):
    from playwright.sync_api import sync_playwright
    argv = sys.argv[1:] if argv is None else argv
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "svg").mkdir(exist_ok=True)
    for mode in MODES:
        (OUT / "svg" / f"nisse-wallpaper-{mode}-1920x1080.svg").write_text(scene(1920, 1080, mode), encoding="ascii", newline=LF)
    sheet = build_sheet()
    (OUT / "sheet.svg").write_text(sheet, encoding="ascii", newline=LF)
    with sync_playwright() as p:
        browser = p.chromium.launch()
        page = browser.new_page()
        (OUT / "sheet.png").write_bytes(_screenshot(page, sheet, SHEET_W, SHEET_H))
        if "--all" in argv:
            pkg = ROOT / "out" / "wallpapers" / "nisse"
            (pkg / "contents").mkdir(parents=True, exist_ok=True)
            (pkg / "metadata.json").write_text(metadata(), encoding="ascii", newline=LF)
            for folder, mode in (("images", "light"), ("images_dark", "dark")):
                (pkg / "contents" / folder).mkdir(parents=True, exist_ok=True)
                for sw, sh in SIZES:
                    (pkg / "contents" / folder / f"{sw}x{sh}.png").write_bytes(_screenshot(page, scene(sw, sh, mode), sw, sh))
            (pkg / "contents" / "screenshot.png").write_bytes(_screenshot(page, scene(600, 338, "dark"), 600, 338))
            print(f"wrote the Plasma wallpaper folder to {pkg}")
        browser.close()
    print(f"wrote the review sheet and the 16:9 masters to {OUT}")


if __name__ == "__main__":
    sys.exit(main())
