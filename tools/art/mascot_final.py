"""N-402, the final mascot set: the master gnome as a head badge, standing, waving and working with the pickaxe.

The master is Bert's round-5 pick: a cap over one round Paper beard-body with the robe's face, and the pickaxe carried
across the body in two hands as the working pose. The cap is the LOGO's hat, exactly: its path and its cuff are read
from tools/logo/build.py (HAT), so the mascot cannot drift from the mark. See assets/art/STYLE.md for the rules.

    python tools/art/mascot_final.py            writes assets/art/mascot/*.svg and sheet.png
"""
import ast
import base64
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from mascot_options import (DIV, EMBER, EMBER_P, EMBER_T, FIG_H, FIG_W, HEAD_BOX, INK, MUTED, OUTL, PAPER,  # noqa: E402
                            SURF, SURF2)
from mascot_round4 import along, beard_body, boots, pick  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "assets" / "art" / "mascot"
LOGO_BUILD = ROOT / "tools" / "logo" / "build.py"

HEADER = '<?xml version="1.0" encoding="UTF-8"?>\n<!-- SPDX-License-Identifier: GPL-2.0-or-later -->\n' \
         '<!-- Generated by tools/art/mascot_final.py (N-402). Ember palette only. -->\n'


def logo_hat():
    """The logo's hat as written in tools/logo/build.py: (path d, (cuff x, y, width, height, radius)). Read, not copied."""
    tree = ast.parse(LOGO_BUILD.read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(getattr(t, "id", None) == "HAT" for t in node.targets):
            markup = ast.literal_eval(node.value)
            d = re.search(r'<path d="([^"]+)"', markup).group(1)
            rect = re.search(r'<rect x="(-?[\d.]+)" y="(-?[\d.]+)" width="([\d.]+)" height="([\d.]+)" rx="([\d.]+)"', markup)
            return d, rect.groups()
    raise RuntimeError("HAT not found in tools/logo/build.py")


HAT_D, (CUFF_X, CUFF_Y, CUFF_W, CUFF_H, CUFF_RX) = logo_hat()
HAT_TOP = 112.5   # how far the hook rises above the cuff's bottom edge, in the logo's own units (measured from HAT_D)


def doc(w, h, title, body, defs=""):
    d = f"  <defs>{defs}</defs>\n" if defs else ""
    return (HEADER + f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}" '
            f'role="img" aria-label="{title}">\n  <title>{title}</title>\n{d}  {body}\n</svg>\n')


def spec():
    """The one width (the logo cuff, scaled) and where the head ends and the body begins (y)."""
    return dict(cap_w=170, face_w=170, beard_w=170, cap_base=350, head_bottom=404, body_top=404)


def cap_scale():
    return spec()["cap_w"] / float(CUFF_W)


def cap_top():
    return spec()["cap_base"] - HAT_TOP * cap_scale()


def cap():
    """The logo's hat: the same path and the same cuff, one flat Ember shape, scaled so the cuff is the one width."""
    sp = spec()
    return (f'<g id="cap" transform="translate(200 {sp["cap_base"]}) scale({cap_scale():.4f})" fill="{EMBER}">'
            f'<path d="{HAT_D}"/><rect x="{CUFF_X}" y="{CUFF_Y}" width="{CUFF_W}" height="{CUFF_H}" rx="{CUFF_RX}"/></g>')


def hand(x, y, r=15, ident="hand"):
    return f'<circle id="{ident}" cx="{x:.1f}" cy="{y:.1f}" r="{r}" fill="{EMBER_T}"/>'


def master_art():
    """The master with no feet, hands or tool: the logo's hat, the robe's face and the round beard-body."""
    sp = spec()
    base = sp["cap_base"]
    eyes = "".join(f'<circle id="eye" cx="{200 + dx}" cy="{base + 28}" r="9" fill="{INK}"/>' for dx in (-36, 36))
    return (f'<rect id="face" x="{200 - sp["face_w"] / 2}" y="{base - 8}" width="{sp["face_w"]}" height="74" rx="24" fill="{EMBER_T}"/>'
            + beard_body(sp["beard_w"], sp["body_top"], 534, PAPER)
            + f'<circle id="nose" cx="200" cy="{sp["body_top"] + 2}" r="19" fill="{EMBER}"/>' + eyes + cap())


FEET = boots(538, 34)
HAND_L, HAND_R = (112, 474), (288, 474)


def standing():
    return doc(FIG_W, FIG_H, "nisse gnome, standing", FEET + master_art() + hand(*HAND_L) + hand(*HAND_R))


def waving():
    # the arm comes out from BEHIND the beard (drawn first); the hands are circles IN FRONT of it (drawn last), as when standing
    arm = (f'<line id="wave-arm" x1="262" y1="452" x2="324" y2="398" stroke="{EMBER_T}" stroke-width="20" stroke-linecap="round"/>')
    wave = (f'<g id="wave"><circle id="wave-hand" cx="324" cy="390" r="18" fill="{EMBER_T}"/>'
            f'<path d="M356 366 Q370 384 362 406" fill="none" stroke="{OUTL}" stroke-width="5" stroke-linecap="round"/>'
            f'<path d="M370 350 Q392 378 380 412" fill="none" stroke="{OUTL}" stroke-width="5" stroke-linecap="round"/></g>')
    return doc(FIG_W, FIG_H, "nisse gnome, waving", arm + FEET + master_art() + hand(*HAND_L) + wave)


def working():
    # the pickaxe carried flat across the body at belly height, the head to the right, a hand on each side of the belly
    px, py = 338, 474
    h1, h2 = along(px, py, 78, 90), along(px, py, 196, 90)
    return doc(FIG_W, FIG_H, "nisse gnome, working with the pickaxe",
               FEET + master_art() + pick(px, py, 300, head=MUTED, tilt=90) + hand(*h1) + hand(*h2))


def head():
    """The avatar: a 512 disc on the surface color, the hill of the logo behind, the head cropped tight."""
    s = 1.05
    ty = 60 - cap_top() * s   # the hook lands 60 down, where the disc is wide enough to hold it
    clip = '<clipPath id="disc"><circle cx="256" cy="256" r="236"/></clipPath>'
    hill = f'<path d="M0 410 C120 380 200 372 256 374 C330 376 400 384 512 420 V512 H0 Z" fill="{SURF2}"/>'
    body = (f'<circle cx="256" cy="256" r="236" fill="{SURF}"/>\n  <g clip-path="url(#disc)">{hill}'
            f'<g transform="translate({256 - 200 * s:.1f} {ty:.1f}) scale({s})">{master_art()}</g></g>')
    return doc(HEAD_BOX, HEAD_BOX, "nisse gnome, head badge", body, clip)


def build_all():
    return {
        "nisse-gnome-head": head(),
        "nisse-gnome-standing": standing(),
        "nisse-gnome-waving": waving(),
        "nisse-gnome-working": working(),
    }


def _inner(svg):
    start = svg.index("<defs>") if "<defs>" in svg else svg.index("<title>")
    return svg[start:svg.rindex("</svg>")]


SHEET_W, SHEET_H = 1840, 1060


def build_sheet():
    allsvg = build_all()
    labels = (("nisse-gnome-head", "head badge", 0.8, 0), ("nisse-gnome-standing", "standing", 0.74, 1),
              ("nisse-gnome-waving", "waving", 0.74, 2), ("nisse-gnome-working", "working with the pickaxe", 0.74, 3))
    parts = []
    for key, label, sc, i in labels:
        x0 = 40 + i * 440
        parts.append(f'<g transform="translate({x0 + 15} 110) scale({sc})">{_inner(allsvg[key])}</g>'
                     f'<text x="{x0 + 20}" y="70" font-family="Nunito, sans-serif" font-size="30" fill="{MUTED}">{label}</text>')
    head_inner = _inner(allsvg["nisse-gnome-head"])
    for bg, tx, fg in ((INK, 60, MUTED), (PAPER, 940, DIV)):
        parts.append(f'<rect x="{tx - 20}" y="720" width="860" height="260" fill="{bg}"/>')
        x = tx + 20
        for w in (128, 96, 64, 48, 24):
            parts.append(f'<g transform="translate({x} {760 + (128 - w) / 2:.0f}) scale({w / 512:.4f})">{head_inner}</g>')
            x += w + 20
        parts.append(f'<text x="{tx + 20}" y="950" font-family="Nunito, sans-serif" font-size="22" fill="{fg}">'
                     f'avatar sizes 128, 96, 64, 48 and 24 px</text>')
    body = f'<rect width="{SHEET_W}" height="{SHEET_H}" fill="{INK}"/>' + "".join(parts)
    return doc(SHEET_W, SHEET_H, "nisse gnome mascot: head badge, standing, waving, working", body)


def main():
    from playwright.sync_api import sync_playwright
    OUT.mkdir(parents=True, exist_ok=True)
    for name, svg in build_all().items():
        (OUT / f"{name}.svg").write_text(svg, encoding="ascii", newline="\n")
    sheet = build_sheet()
    (OUT / "sheet.svg").write_text(sheet, encoding="ascii", newline="\n")
    uri = "data:image/svg+xml;base64," + base64.b64encode(sheet.encode("ascii")).decode()
    with sync_playwright() as p:
        b = p.chromium.launch()
        pg = b.new_page(viewport={"width": SHEET_W, "height": SHEET_H})
        pg.set_content(f'<html><body style="margin:0"><img src="{uri}" width="{SHEET_W}" height="{SHEET_H}" style="display:block"></body></html>')
        pg.wait_for_function("document.images[0].complete")
        (OUT / "sheet.png").write_bytes(pg.screenshot(clip={"x": 0, "y": 0, "width": SHEET_W, "height": SHEET_H}))
        b.close()
    print(f"wrote {len(build_all())} drawings, sheet.svg and sheet.png to {OUT}")


if __name__ == "__main__":
    sys.exit(main())
