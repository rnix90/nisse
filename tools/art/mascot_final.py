"""N-402, the final mascot set: the master gnome as a head badge, standing, waving and working with the pickaxe.

The master is Bert's round-5 pick: the gumdrop body (cap over one round Paper beard-body) with the robe's face, and
the pickaxe carried across the body in two hands as the working pose. See assets/art/STYLE.md for the rules.

    python tools/art/mascot_final.py            writes assets/art/mascot/*.svg and sheet.png
"""
import base64
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from mascot_options import DIV, EMBER_T, FIG_H, FIG_W, INK, MUTED, OUTL, PAPER, SURF  # noqa: E402
from mascot_round4 import boots, hand  # noqa: E402
from mascot_round5 import arm, master_art, master_badge, pose_pick_carry  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "assets" / "art" / "mascot"

HEADER = '<?xml version="1.0" encoding="UTF-8"?>\n<!-- SPDX-License-Identifier: GPL-2.0-or-later -->\n' \
         '<!-- Generated by tools/art/mascot_final.py (N-402). Ember palette only. -->\n'


def doc(w, h, title, body):
    return (HEADER + f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}" '
            f'role="img" aria-label="{title}">\n  <title>{title}</title>\n  {body}\n</svg>\n')


def standing():
    return doc(FIG_W, FIG_H, "nisse gnome, standing", boots(538, 34) + master_art() + hand(104, 452) + hand(296, 452))


def waving():
    wave = (f'<g id="wave">{arm(288, 414, 326, 364)}{hand(326, 354, 18)}'
            f'<path d="M358 330 Q372 348 364 370" fill="none" stroke="{OUTL}" stroke-width="5" stroke-linecap="round"/>'
            f'<path d="M372 314 Q394 342 382 376" fill="none" stroke="{OUTL}" stroke-width="5" stroke-linecap="round"/></g>')
    return doc(FIG_W, FIG_H, "nisse gnome, waving", boots(538, 34) + master_art() + hand(104, 452) + wave)


def working():
    return doc(FIG_W, FIG_H, "nisse gnome, working with the pickaxe", boots(538, 34) + master_art() + pose_pick_carry())


def head():
    return master_badge().replace("nisse gnome master, head badge", "nisse gnome, head badge")


def build_all():
    return {
        "nisse-gnome-head": head(),
        "nisse-gnome-standing": standing(),
        "nisse-gnome-waving": waving(),
        "nisse-gnome-working": working(),
    }


def _inner(svg):
    start = svg.index("<defs>") if "<defs>" in svg else svg.index("<title>")
    return svg[start:svg.rindex("</svg>")]


SHEET_W, SHEET_H = 1840, 1060


def build_sheet():
    allsvg = build_all()
    labels = (("nisse-gnome-head", "head badge", 0.8, 0), ("nisse-gnome-standing", "standing", 0.74, 1),
              ("nisse-gnome-waving", "waving", 0.74, 2), ("nisse-gnome-working", "working with the pickaxe", 0.74, 3))
    parts = []
    for key, label, sc, i in labels:
        x0 = 40 + i * 440
        parts.append(f'<g transform="translate({x0 + 15} 110) scale({sc})">{_inner(allsvg[key])}</g>'
                     f'<text x="{x0 + 20}" y="70" font-family="Nunito, sans-serif" font-size="30" fill="{MUTED}">{label}</text>')
    head_inner = _inner(allsvg["nisse-gnome-head"])
    for bg, tx, fg in ((INK, 60, MUTED), (PAPER, 940, DIV)):
        parts.append(f'<rect x="{tx - 20}" y="720" width="860" height="260" fill="{bg}"/>')
        x = tx + 20
        for w in (128, 96, 64, 48, 24):
            parts.append(f'<g transform="translate({x} {760 + (128 - w) / 2:.0f}) scale({w / 512:.4f})">{head_inner}</g>')
            x += w + 20
        parts.append(f'<text x="{tx + 20}" y="950" font-family="Nunito, sans-serif" font-size="22" fill="{fg}">'
                     f'avatar sizes 128, 96, 64, 48 and 24 px</text>')
    body = f'<rect width="{SHEET_W}" height="{SHEET_H}" fill="{INK}"/>' + "".join(parts)
    return doc(SHEET_W, SHEET_H, "nisse gnome mascot: head badge, standing, waving, working", body)


def main():
    from playwright.sync_api import sync_playwright
    OUT.mkdir(parents=True, exist_ok=True)
    for name, svg in build_all().items():
        (OUT / f"{name}.svg").write_text(svg, encoding="ascii", newline="\n")
    sheet = build_sheet()
    (OUT / "sheet.svg").write_text(sheet, encoding="ascii", newline="\n")
    uri = "data:image/svg+xml;base64," + base64.b64encode(sheet.encode("ascii")).decode()
    with sync_playwright() as p:
        b = p.chromium.launch()
        pg = b.new_page(viewport={"width": SHEET_W, "height": SHEET_H})
        pg.set_content(f'<html><body style="margin:0"><img src="{uri}" width="{SHEET_W}" height="{SHEET_H}" style="display:block"></body></html>')
        pg.wait_for_function("document.images[0].complete")
        (OUT / "sheet.png").write_bytes(pg.screenshot(clip={"x": 0, "y": 0, "width": SHEET_W, "height": SHEET_H}))
        b.close()
    print(f"wrote {len(build_all())} drawings, sheet.svg and sheet.png to {OUT}")


if __name__ == "__main__":
    sys.exit(main())
