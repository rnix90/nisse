# ------------------------------------------------------------------ assembling
PICK_X, PICK_TOP, PICK_LEN = 312, 330, 220


def figure(title, head_g, body, sleeve, hs, hy, edge=None, pose="work"):
    hx, hy2 = along(PICK_X, PICK_TOP, 112)
    head_tr = f"translate(200 {hy}) scale({hs}) translate(-200 -258)"
    left = arm([(150, 376), (108, 426), (146, 458)], sleeve, edge) + (
        f'<circle cx="146" cy="458" r="16" fill="{EMBER_T}" stroke="{EMBER_P}" stroke-width="3"/>')
    if pose == "work":
        right = pick(PICK_X, PICK_TOP, PICK_LEN) + arm([(250, 376), (290, 424), (hx, hy2)], sleeve, edge) + fist(hx, hy2)
    else:  # wave: the right arm up, an open hand, two small motion arcs
        right = (arm([(250, 376), (306, 354), (322, 292)], sleeve, edge) + open_hand(322, 276) +
                 f'<path d="M352 252 Q366 268 358 288" fill="none" stroke="{OUTL}" stroke-width="5" stroke-linecap="round"/>'
                 f'<path d="M366 236 Q388 262 376 296" fill="none" stroke="{OUTL}" stroke-width="5" stroke-linecap="round"/>')
    b = (f'<ellipse cx="200" cy="560" rx="132" ry="14" fill="{SURF}"/>' + body + left + right +
         f'<g transform="{head_tr}">{head_g}</g>')
    return doc(FIG_W, FIG_H, title, b)


def badge(title, head_g, s, top, tip=6):
    """The hill-and-stars disc of the logo with the head cropped tight: the cap tip lands near the top of the disc."""
    cy = tip - s * top + 258 * s
    stars = "".join(f'<circle cx="{x}" cy="{y}" r="{r}" fill="{PAPER}"/>'
                    for x, y, r in ((74, 150, 4), (440, 130, 5), (56, 252, 3), (456, 232, 3), (404, 62, 3), (100, 76, 3)))
    hill = (f'<path d="M0 392 C120 360 200 352 256 354 C330 356 400 364 512 402 V512 H0 Z" fill="{SURF2}"/>'
            f'<path d="M0 392 C120 360 200 352 256 354 C330 356 400 364 512 402" fill="none" stroke="{DIV}" stroke-width="6"/>')
    clip = '<clipPath id="disc"><circle cx="256" cy="256" r="236"/></clipPath>'
    tr = f"translate({256 - 200 * s:.1f} {cy - 258 * s:.1f}) scale({s})"
    body = (f'<circle cx="256" cy="256" r="236" fill="{SURF}"/>\n  <g clip-path="url(#disc)">{stars}{hill}'
            f'<g transform="{tr}">{head_g}</g></g>')
    return doc(HEAD_BOX, HEAD_BOX, title, body, clip)


# num, name, head kwargs, body, sleeve, edge, (hs, hy), badge scale
def _options():
    return {
        "1": ("tomte", dict(cs=1.15, bb=440), body_bell(OUTL, PAPER), OUTL, None, (0.78, 206), 1.3),
        "2": ("wee tomte", dict(cs=1.0, bb=388, eyes="dot", eye_r=14, brows=False, mustache=False, smile=True, cheek_r=13, beard_w=0.92),
              body_bean(MUTED, PAPER), MUTED, None, (0.92, 218), 1.15),
        "3": ("digger", dict(cs=1.1, bb=408, goggles=True, big_mustache=True, beard_w=0.8),
              body_bell(DIV, MUTED, edge=OUTL), DIV, OUTL, (0.84, 214), 1.25),
        "4": ("elder", dict(cs=1.25, bb=440, beard=MUTED, eye_r=9, beard_w=1.05),
              body_tall(PAPER, OUTL), PAPER, None, (0.72, 212), 1.3),
    }


def build_all():
    out = {}
    for n, (name, hk, body, sleeve, edge, (hs, hy), bs) in _options().items():
        head = tomte_head(**hk)
        out[f"{n}-head"] = badge(f"nisse gnome round 3 option {n}, head badge: {name}", head, bs, cap_top(hk["cs"]))
        out[f"{n}-figure"] = figure(f"nisse gnome round 3 option {n}, figure: {name}, with a pickaxe", head, body, sleeve,
                                    hs, hy, edge)
    name, hk, body, sleeve, edge, (hs, hy), _ = _options()["1"]
    out["1-wave"] = figure("nisse gnome round 3 option 1, figure: tomte, waving", tomte_head(**hk), body, sleeve, hs, hy,
                           edge, pose="wave")
    return out


def _inner(svg):
    start = svg.index("<defs>") if "<defs>" in svg else svg.index("<title>")
    return svg[start:svg.rindex("</svg>")]


SHEET_W, SHEET_H = 1840, 1620


def build_sheet():
    col_w, margin, row_h = 440, 40, 800
    allsvg = build_all()
    parts = []
    for i, (n, (name, *_)) in enumerate(_options().items()):
        x0 = margin + i * col_w
        head_inner = _inner(allsvg[f"{n}-head"]).replace('id="disc"', f'id="disc-{n}"').replace("url(#disc)", f"url(#disc-{n})")
        parts.append(
            f'<g transform="translate({x0 + 105} 90) scale(0.45)">{head_inner}</g>'
            f'<g transform="translate({x0 + 76} 334) scale(0.74)">{_inner(allsvg[f"{n}-figure"])}</g>'
            f'<text x="{x0 + 30}" y="70" font-family="Nunito, sans-serif" font-size="54" font-weight="800" fill="{PAPER}">{n}</text>'
            f'<text x="{x0 + 100}" y="70" font-family="Nunito, sans-serif" font-size="30" fill="{MUTED}">{name}</text>')
    # row 2: the waving pose, and the badges at the sizes an avatar is really seen
    y0 = row_h
    parts.append(f'<g transform="translate({margin + 76} {y0 + 70}) scale(0.74)">{_inner(allsvg["1-wave"])}</g>'
                 f'<text x="{margin + 30}" y="{y0 + 56}" font-family="Nunito, sans-serif" font-size="30" fill="{MUTED}">1 tomte, waving</text>')
    for k, (bg, ty) in enumerate(((SURF, y0 + 60), (PAPER, y0 + 290))):
        parts.append(f'<rect x="{margin + 470}" y="{ty}" width="1290" height="200" fill="{bg}"/>')
        x = margin + 490
        for n in _options():
            inner = _inner(allsvg[f"{n}-head"]).replace('id="disc"', f'id="disc-{n}"').replace("url(#disc)", f"url(#disc-{n})")
            for w in (96, 48, 24):
                parts.append(f'<g transform="translate({x} {ty + 24 + (96 - w) / 2:.0f}) scale({w / 512:.4f})">{inner}</g>')
                x += w + 10
            x += 34
        parts.append(f'<text x="{margin + 490}" y="{ty + 170}" font-family="Nunito, sans-serif" font-size="22" fill="{MUTED if bg == INK else DIV}">'
                     f'avatar sizes 96, 48 and 24 px</text>')
    body = f'<rect width="{SHEET_W}" height="{SHEET_H}" fill="{INK}"/>' + "".join(parts)
    return doc(SHEET_W, SHEET_H, "nisse gnome mascot, round 3: four tomte variants and a waving pose", body)


def main():
    from playwright.sync_api import sync_playwright
    OUT.mkdir(parents=True, exist_ok=True)
    for name, svg in build_all().items():
        (OUT / f"{name}.svg").write_text(svg, encoding="ascii", newline="\n")
    sheet = build_sheet()
    (OUT / "sheet.svg").write_text(sheet, encoding="ascii", newline="\n")
    uri = "data:image/svg+xml;base64," + base64.b64encode(sheet.encode("ascii")).decode()
    with sync_playwright() as p:
        b = p.chromium.launch()
        pg = b.new_page(viewport={"width": SHEET_W, "height": SHEET_H})
        pg.set_content(f'<html><body style="margin:0"><img src="{uri}" width="{SHEET_W}" height="{SHEET_H}" style="display:block"></body></html>')
        pg.wait_for_function("document.images[0].complete")
        (OUT / "sheet.png").write_bytes(pg.screenshot(clip={"x": 0, "y": 0, "width": SHEET_W, "height": SHEET_H}))
        b.close()
    print(f"wrote {len(build_all())} drawings, sheet.svg and sheet.png to {OUT}")


if __name__ == "__main__":
    sys.exit(main())
