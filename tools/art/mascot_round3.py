HEADER = '<?xml version="1.0" encoding="UTF-8"?>\n<!-- SPDX-License-Identifier: GPL-2.0-or-later -->\n' \
         '<!-- Generated by tools/art/mascot_round3.py (N-402 round 3). Ember palette only. -->\n'

PICK_HALF_SPAN = 71   # spike 80 to the right, adze 62 to the left: the pick head spans 142 units
TILT = 6.8            # degrees the pickaxe leans


def doc(w, h, title, body, defs=""):
    d = f"  <defs>{defs}</defs>\n" if defs else ""
    return (HEADER + f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}" '
            f'role="img" aria-label="{title}">\n  <title>{title}</title>\n{d}  {body}\n</svg>\n')


# ------------------------------------------------------------------ the pickaxe, hands and arms
def pick(x, y_top, length, tilt=TILT):
    """Group id pickaxe: a warm handle, a hub, a curved spike (right) and a flat adze (left), leaning by tilt degrees."""
    y = y_top
    spike = (f"M{x + 8} {y - 22} C{x + 44} {y - 24} {x + 70} {y - 8} {x + 80} {y + 16} "
             f"C{x + 60} {y + 2} {x + 34} {y + 4} {x + 8} {y + 10} Z")
    spike_shade = (f"M{x + 8} {y + 10} C{x + 34} {y + 4} {x + 60} {y + 2} {x + 80} {y + 16} "
                   f"C{x + 60} {y + 12} {x + 34} {y + 12} {x + 8} {y + 18} Z")
    adze = f"M{x - 8} {y - 24} L{x - 52} {y - 30} L{x - 62} {y + 22} L{x - 8} {y + 12} Z"
    adze_shade = f"M{x - 8} {y + 4} L{x - 60} {y + 10} L{x - 62} {y + 22} L{x - 8} {y + 12} Z"
    return (f'<g id="pickaxe" transform="rotate({tilt} {x} {y})">'
            f'<line x1="{x}" y1="{y - 4}" x2="{x}" y2="{y + length}" stroke="{EMBER_P}" stroke-width="17" stroke-linecap="round"/>'
            f'<path id="pick-adze" d="{adze}" fill="{MUTED}"/><path d="{adze_shade}" fill="{OUTL}"/>'
            f'<path id="pick-spike" d="{spike}" fill="{MUTED}"/><path d="{spike_shade}" fill="{OUTL}"/>'
            f'<rect x="{x - 13}" y="{y - 12}" width="26" height="36" rx="8" fill="{OUTL}"/></g>')


def along(x, y_top, d, tilt=TILT):
    """The point d units down a handle that leans by tilt degrees from its top (x, y_top)."""
    t = math.radians(tilt)
    return x - d * math.sin(t), y_top + d * math.cos(t)


def fist(x, y, tilt=TILT, r=16):
    """A fist wrapped round a handle: a rounded block with finger gaps and a thumb."""
    return (f'<g transform="rotate({tilt} {x:.1f} {y:.1f})">'
            f'<rect x="{x - r:.1f}" y="{y - r * 0.95:.1f}" width="{2 * r}" height="{1.9 * r:.1f}" rx="{r * 0.6:.1f}" '
            f'fill="{EMBER_T}" stroke="{EMBER_P}" stroke-width="3"/>'
            f'<line x1="{x - r * 0.8:.1f}" y1="{y - r * 0.28:.1f}" x2="{x + r * 0.8:.1f}" y2="{y - r * 0.28:.1f}" stroke="{EMBER_P}" stroke-width="3" stroke-linecap="round"/>'
            f'<line x1="{x - r * 0.8:.1f}" y1="{y + r * 0.34:.1f}" x2="{x + r * 0.8:.1f}" y2="{y + r * 0.34:.1f}" stroke="{EMBER_P}" stroke-width="3" stroke-linecap="round"/>'
            f'<ellipse cx="{x - r * 0.9:.1f}" cy="{y - r * 0.7:.1f}" rx="{r * 0.34:.1f}" ry="{r * 0.5:.1f}" fill="{EMBER_T}" '
            f'stroke="{EMBER_P}" stroke-width="3"/></g>')


def arm(points, color, edge=None):
    """A bent sleeve through the points, with an edge line under it when the robe is dark."""
    d = "M" + " L".join(f"{x:.1f} {y:.1f}" for x, y in points)
    out = ""
    if edge:
        out += (f'<path d="{d}" fill="none" stroke="{edge}" stroke-width="37" stroke-linecap="round" stroke-linejoin="round"/>')
    return out + f'<path d="{d}" fill="none" stroke="{color}" stroke-width="30" stroke-linecap="round" stroke-linejoin="round"/>'


def open_hand(x, y):
    return (f'<circle cx="{x}" cy="{y}" r="18" fill="{EMBER_T}" stroke="{EMBER_P}" stroke-width="3"/>'
            f'<ellipse cx="{x - 16}" cy="{y + 6}" rx="8" ry="12" fill="{EMBER_T}" stroke="{EMBER_P}" stroke-width="3" transform="rotate(30 {x - 16} {y + 6})"/>'
            + "".join(f'<ellipse cx="{x + dx}" cy="{y - 20}" rx="6" ry="11" fill="{EMBER_T}" stroke="{EMBER_P}" stroke-width="3" '
                      f'transform="rotate({a} {x + dx} {y - 20})"/>' for dx, a in ((-8, -18), (2, -4), (12, 12))))


# ------------------------------------------------------------------ the head: one tomte, four settings (local coords, face centre 200,258)
def tomte_head(cs=1.15, bb=440, beard=PAPER, eyes="dot", eye_r=10, brows=True, mustache=True, smile=False,
               cheek_r=10, goggles=False, big_mustache=False, beard_w=1.0):
    cap_y = 230
    cap_x = 200 - 85 * cs
    w = 88 * beard_w
    beard_d = (f"M{200 - w} 280 C{200 - w - 10} {bb - 100} {200 - 54 * beard_w} {bb - 24} 200 {bb} "
               f"C{200 + 54 * beard_w} {bb - 24} {200 + w + 10} {bb - 100} {200 + w} 280 "
               f"C{200 + w - 22} 304 238 310 200 310 C162 310 {200 - w + 22} 304 {200 - w} 280 Z")
    out = (f'<circle cx="200" cy="258" r="80" fill="{EMBER_T}"/>'
           f'<path d="{beard_d}" fill="{beard}"/>')
    if mustache:
        sw = 46 if big_mustache else 40
        out += (f'<ellipse cx="{200 - sw * 0.8:.0f}" cy="306" rx="{sw}" ry="{19 if big_mustache else 17}" fill="{beard}" transform="rotate(14 {200 - sw * 0.8:.0f} 306)"/>'
                f'<ellipse cx="{200 + sw * 0.8:.0f}" cy="306" rx="{sw}" ry="{19 if big_mustache else 17}" fill="{beard}" transform="rotate(-14 {200 + sw * 0.8:.0f} 306)"/>')
    if eyes == "dot":
        out += eye(168, 262, eye_r) + eye(232, 262, eye_r)
    else:
        out += (f'<path d="M148 266 Q168 244 188 266" fill="none" stroke="{INK}" stroke-width="8" stroke-linecap="round"/>'
                f'<path d="M212 266 Q232 244 252 266" fill="none" stroke="{INK}" stroke-width="8" stroke-linecap="round"/>')
    if brows:
        out += (f'<path d="M146 252 L186 246" stroke="{PAPER}" stroke-width="9" stroke-linecap="round"/>'
                f'<path d="M214 246 L254 252" stroke="{PAPER}" stroke-width="9" stroke-linecap="round"/>')
    out += (f'<circle cx="150" cy="290" r="{cheek_r}" fill="{EMBER_P}"/><circle cx="250" cy="290" r="{cheek_r}" fill="{EMBER_P}"/>'
            f'<circle cx="200" cy="292" r="22" fill="{EMBER}"/><circle cx="192" cy="284" r="6" fill="{EMBER_T}"/>')
    if smile:
        out += f'<path d="M180 326 Q200 344 220 326" fill="none" stroke="{INK}" stroke-width="7" stroke-linecap="round"/>'
    out += cap(CURL, CURL_SHADE, cap_x, cap_y, cs)
    if goggles:
        out += (f'<rect x="{200 - 62 * cs:.0f}" y="{cap_y - 28 * cs:.0f}" width="{124 * cs:.0f}" height="{12 * cs:.0f}" rx="6" fill="{DIV}"/>'
                + "".join(f'<circle cx="{200 + dx}" cy="{cap_y - 36 * cs:.0f}" r="{25 * cs:.0f}" fill="{OUTL}"/>'
                          f'<circle cx="{200 + dx}" cy="{cap_y - 36 * cs:.0f}" r="{16 * cs:.0f}" fill="{INFO}"/>'
                          f'<circle cx="{200 + dx + 5}" cy="{cap_y - 42 * cs:.0f}" r="5" fill="{PAPER}"/>' for dx in (-29, 29)))
    return out


def cap_top(cs):
    return 230 - 192 * cs


# ------------------------------------------------------------------ bodies (neck near y 332, feet at y 548)
def _edge(edge):
    return f' stroke="{edge}" stroke-width="4" stroke-linejoin="round"' if edge else ""


