"""N-402, round 3: four tomte variants and a waving pose, built from the two critique reviews.

What the reviews asked for, and where it lands here:
  - the round-2 tomte is the master (hooked cap from the logo, eyes under the brim, nose out of a beard)
  - beard to chest length, no elf ears, expression from brows or a smile
  - robes that are not blue, green or mustard; dark robes get an edge so they show on Ink
  - a pickaxe with a pointed spike on one side and a flat adze on the other, a warm handle, a hand that wraps it
  - a tight avatar crop on the hill-and-stars disc of the logo
Scripted SVG, flat shapes, Ember palette hexes only, no gradients or filters.

    python tools/art/mascot_round3.py            writes assets/art/mascot-round3/*.svg, sheet.png, small-sizes.png
"""
