"""N-409: the nisse icons that replace four Breeze ones, drawn from the Ember palette and the logo.

  preferences-system     Breeze draws two sliders; nisse draws a gear (Paper on the Ink tile, an Ember hub).
  utilities-terminal     the terminal-under-the-cap idea from the logo exploration (reserved for a terminal, roadmap 1.10): a
                         Paper prompt window with the LOGO's exact hat on top, on the Ink tile.
  anaconda               the installer's icon: the nisse logo on a disk (a drive body, a vent, a status light), replacing the tile.
  start-here-kde-plasma  Plasma's start icon: its three colored dots stay ("use these colors", Bert) and the nisse disc takes the
                         chevron's place. It carries Plasma's own recolor class, so Plasma draws the disc in the text color of the
                         look; the dark and light overlay themes differ only in the default.

Base: Breeze with two small overlay themes (Bert's choice, 2026-11-17): `nisse_icons` (inherits breeze) and `nisse_icons_dark`
(inherits breeze-dark) carry just preferences-system, utilities-terminal and start-here-kde-plasma. `anaconda` is installed by
nisse-branding (tools/logo/build_system.py uses `build_all()["anaconda"]`).

    python tools/art/icons.py          writes assets/art/icons/ (the two themes and sheet.png)
"""
import base64
import importlib.util
import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))
import mascot_final  # noqa: E402
import wallpaper  # noqa: E402

OUT = ROOT / "assets" / "art" / "icons"
LF = chr(10)
INK, PAPER, EMBER, SURF2 = "#1b2330", "#f6f2e9", "#e0623f", "#2b3749"
TEETH = 8
HEADER = ('<?xml version="1.0" encoding="UTF-8"?>' + LF + '<!-- SPDX-License-Identifier: GPL-2.0-or-later -->' + LF
          + '<!-- Generated by tools/art/icons.py (N-409). Ember palette and the nisse logo. -->' + LF)


def _logo_build():
    spec = importlib.util.spec_from_file_location("nisse_logo_build", ROOT / "tools" / "logo" / "build.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def f1(v):
    return f"{v:.1f}"


def doc(size, title, body, defs=""):
    d = f"<defs>{defs}</defs>" if defs else ""
    return (HEADER + f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {size} {size}" width="{size}" height="{size}" role="img" '
            f'aria-label="{title}">' + LF + f"  <title>{title}</title>" + LF + f"  {d}{body}" + LF + "</svg>" + LF)


def tile():
    return f'<rect id="tile" width="96" height="96" rx="21" fill="{INK}"/>'


def gear():
    verts = []
    for i in range(TEETH):
        a0 = i * 360 / TEETH
        for da, rad in ((-13.5, 23), (-8, 31), (8, 31), (13.5, 23)):
            a = math.radians(a0 + da - 90)
            verts.append((48 + rad * math.cos(a), 48 + rad * math.sin(a)))
    return (f'<path id="gear" d="{wallpaper.rounded(verts, 2.4)}" fill="{PAPER}"/>'
            f'<circle cx="48" cy="48" r="11" fill="{INK}"/><circle id="hub" cx="48" cy="48" r="4.6" fill="{EMBER}"/>')


def preferences_system():
    return doc(96, "nisse gear icon", tile() + gear())


def utilities_terminal():
    window = f'<rect id="window" x="14" y="50" width="68" height="32" rx="8" fill="{PAPER}"/>'
    prompt = (f'<g id="prompt"><polyline points="26,58 35,65.5 26,73" fill="none" stroke="{INK}" stroke-width="5" stroke-linecap="round" '
              f'stroke-linejoin="round"/><line x1="43" y1="73" x2="58" y2="73" stroke="{EMBER}" stroke-width="5" stroke-linecap="round"/></g>')
    cap = (f'<g id="cap" transform="translate(48 52) scale(0.4)" fill="{EMBER}"><path d="{mascot_final.HAT_D}"/>'
           f'<rect x="{mascot_final.CUFF_X}" y="{mascot_final.CUFF_Y}" width="{mascot_final.CUFF_W}" height="{mascot_final.CUFF_H}" '
           f'rx="{mascot_final.CUFF_RX}"/></g>')
    return doc(96, "nisse terminal icon", tile() + window + prompt + cap)


def _logo(fill_or_class, ident, x, y, size, mask_id):
    """The nisse round logo (disc with the hat and hill knocked out) as a nested svg."""
    defs, body = _logo_build().icon_parts(PAPER, None)
    defs = defs.replace('id="knockout"', f'id="{mask_id}"')
    body = body.replace("url(#knockout)", f"url(#{mask_id})")
    body = body.replace(f'fill="{PAPER}"', fill_or_class)
    return f'<svg id="{ident}" x="{f1(x)}" y="{f1(y)}" width="{f1(size)}" height="{f1(size)}" viewBox="0 0 512 512">{defs}{body}</svg>'


def anaconda():
    drive = f'<rect id="drive" x="9" y="30" width="78" height="38" rx="9" fill="{PAPER}"/>'
    logo = _logo(f'fill="{INK}"', "logo", 15, 36, 26, "knockout-disk")
    vents = "".join(f'<line x1="52" y1="{y}" x2="68" y2="{y}" stroke="{INK}" stroke-width="3" stroke-linecap="round"/>' for y in (43, 49, 55))
    led = f'<circle id="led" cx="77" cy="49" r="3.6" fill="{EMBER}"/>'
    return doc(96, "nisse installer icon, the logo on a disk", tile() + drive + logo + vents + led)


# Breeze's own three start-here dots (kept: "use these colors"), with its own path data
DOTS = (("#fa8865", "M 18.9 6 C 17.1 6 15.75 7.4 15.75 9.125 C 15.75 10.8 17.1 12.25 18.9 12.25 C 20.6 12.25 22 10.8 22 9.125 C 22 7.4 20.6 6 18.9 6 z"),
        ("#63c605", "M 10.5 25.5 C 8 25.5 6 27.5 6 30 C 6 32.5 8 34.5 10.5 34.5 C 13 34.5 15 32.5 15 30 C 15 27.5 13 25.5 10.5 25.5 z"),
        ("#1b89f3", "M 25.5 45 C 21.9 45 19 47.9 19 51.5 C 19 55.1 21.9 58 25.5 58 C 29.1 58 32 55.1 32 51.5 C 32 47.9 29.1 45 25.5 45 z"))


def start_here(mode):
    color = PAPER if mode == "dark" else INK
    style = f'<style type="text/css" id="current-color-scheme">.ColorScheme-Text {{ color:{color}; }}</style>'
    dots = "".join(f'<path style="fill:{c}" d="{d}"/>' for c, d in DOTS)
    defs, body = _logo_build().icon_parts(PAPER, None)
    defs = defs.replace('id="knockout"', 'id="knockout-start"')
    body = body.replace("url(#knockout)", "url(#knockout-start)").replace(f'fill="{PAPER}"', 'class="ColorScheme-Text" style="fill:currentColor"')
    logo = f'<svg id="logo" x="25" y="11" width="38" height="38" viewBox="0 0 512 512">{defs}{body}</svg>'
    return doc(64, f"nisse start icon, {mode}", dots + logo, style)


def build_all():
    return {"preferences-system": preferences_system(), "utilities-terminal": utilities_terminal(), "anaconda": anaconda(),
            "start-here-kde-plasma-dark": start_here("dark"), "start-here-kde-plasma-light": start_here("light")}


INDEX = """# SPDX-License-Identifier: GPL-2.0-or-later
[Icon Theme]
Name={name}
Comment=The nisse gear, terminal and start icons over {base_name}; every other icon is {base_name}'s
Inherits={base}
Directories=scalable/apps,scalable/places

[scalable/apps]
Size=48
MinSize=8
MaxSize=512
Type=Scalable
Context=Applications

[scalable/places]
Size=48
MinSize=8
MaxSize=512
Type=Scalable
Context=Places
"""


def write_themes():
    svgs = build_all()
    for theme, base, base_name, mode in (("nisse_icons", "breeze", "Breeze", "light"), ("nisse_icons_dark", "breeze-dark", "Breeze Dark", "dark")):
        root = OUT / theme
        (root / "scalable" / "apps").mkdir(parents=True, exist_ok=True)
        (root / "scalable" / "places").mkdir(parents=True, exist_ok=True)
        name = "nisse icons" + (" dark" if mode == "dark" else "")
        (root / "index.theme").write_text(INDEX.format(name=name, base=base, base_name=base_name), encoding="ascii", newline=LF)
        for icon in ("preferences-system", "utilities-terminal"):
            (root / "scalable" / "apps" / f"{icon}.svg").write_text(svgs[icon], encoding="ascii", newline=LF)
        (root / "scalable" / "places" / "start-here-kde-plasma.svg").write_text(svgs[f"start-here-kde-plasma-{mode}"], encoding="ascii", newline=LF)


def _uri(svg):
    return "data:image/svg+xml;base64," + base64.b64encode(svg.encode("ascii")).decode()


def build_sheet():
    """A preview: each icon at 96, 48, 32, 22 and 16 pixels on a dark panel and on a light one."""
    svgs = build_all()
    shown = (("preferences-system", "preferences-system", "dark"), ("utilities-terminal", "utilities-terminal", "dark"),
             ("anaconda", "anaconda (installer)", "dark"), ("start-here-kde-plasma", "start-here-kde-plasma", "both"))
    W, H = 1500, 560
    parts = [f'<rect width="{W}" height="{H}" fill="{INK}"/><rect x="750" width="750" height="{H}" fill="#fffdf8"/>']
    for page, x0 in (("dark", 0), ("light", 750)):
        parts.append(f'<text x="{x0 + 24}" y="34" font-family="Nunito, sans-serif" font-size="24" fill="{"#aab1bd" if page == "dark" else "#5d6573"}">{page} panel</text>')
        for row, (key, label, _) in enumerate(shown):
            svg = svgs[key] if key in svgs else svgs[f"start-here-kde-plasma-{page}"]
            y = 60 + row * 124
            x = x0 + 30
            for size in (96, 48, 32, 22, 16):
                parts.append(f'<image href="{_uri(svg)}" x="{x}" y="{y + (96 - size) / 2:.0f}" width="{size}" height="{size}"/>')
                x += size + 22
            parts.append(f'<text x="{x0 + 380}" y="{y + 54}" font-family="Nunito, sans-serif" font-size="20" fill="{"#aab1bd" if page == "dark" else "#5d6573"}">{label}</text>')
    body = "".join(parts)
    return (HEADER + f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" role="img" aria-label="nisse icons sheet">'
            + LF + f"  <title>nisse icons sheet</title>" + LF + f"  {body}" + LF + "</svg>" + LF), W, H


def render_png(svg, size, page=None):
    """The icon as PNG bytes at size x size, transparent background (Playwright)."""
    from playwright.sync_api import sync_playwright
    own = page is None
    if own:
        p = sync_playwright().start()
        browser = p.chromium.launch()
        page = browser.new_page()
    page.set_viewport_size({"width": size, "height": size})
    page.set_content(f'<html><body style="margin:0;background:transparent"><img src="{_uri(svg)}" width="{size}" height="{size}" style="display:block"></body></html>')
    page.wait_for_function("document.images[0].complete")
    png = page.screenshot(clip={"x": 0, "y": 0, "width": size, "height": size}, omit_background=True)
    if own:
        browser.close()
        p.stop()
    return png


def main():
    from playwright.sync_api import sync_playwright
    write_themes()
    sheet, W, H = build_sheet()
    with sync_playwright() as p:
        browser = p.chromium.launch()
        page = browser.new_page()
        page.set_viewport_size({"width": W, "height": H})
        page.set_content(f'<html><body style="margin:0"><img src="{_uri(sheet)}" width="{W}" height="{H}" style="display:block"></body></html>')
        page.wait_for_function("document.images[0].complete")
        (OUT / "sheet.png").write_bytes(page.screenshot(clip={"x": 0, "y": 0, "width": W, "height": H}))
        browser.close()
    print(f"wrote the two icon themes and sheet.png to {OUT}")


if __name__ == "__main__":
    sys.exit(main())
