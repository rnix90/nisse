PICK_HALF_SPAN = 74  # the pick head spans 2 x this many units (the round-1 head was about 105)


def doc(w, h, title, body, defs=""):
    d = f"  <defs>{defs}</defs>\n" if defs else ""
    return (HEADER + f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}" '
            f'role="img" aria-label="{title}">\n  <title>{title}</title>\n{d}  {body}\n</svg>\n')


# ------------------------------------------------------------------ small parts
def eye(x, y, r=11, dx=0):
    """A dot eye with a highlight; dx shifts the pupil sideways for a glance."""
    return (f'<circle cx="{x + dx}" cy="{y}" r="{r}" fill="{INK}"/>'
            f'<circle cx="{x + dx + r * 0.3:.1f}" cy="{y - r * 0.4:.1f}" r="{r * 0.32:.1f}" fill="{PAPER}"/>')


