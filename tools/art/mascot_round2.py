def pick2(x, y_top, y_bot, flip=False):
    """The round-2 pickaxe (group id pickaxe): a heavy haft, a hub, and a big two-sided steel head."""
    h = PICK_HALF_SPAN
    head = (f"M{x - h} {y_top + 18} C{x - 38} {y_top - 40} {x + 38} {y_top - 40} {x + h} {y_top + 18} "
            f"C{x + 36} {y_top - 2} {x - 36} {y_top - 2} {x - h} {y_top + 18} Z")
    shade = (f"M{x - h} {y_top + 18} C{x - 36} {y_top - 2} {x + 36} {y_top - 2} {x + h} {y_top + 18} "
             f"C{x + 30} {y_top + 8} {x - 30} {y_top + 8} {x - h} {y_top + 18} Z")
    tr = f' transform="translate({2 * x} 0) scale(-1 1)"' if flip else ""
    return (f'<g id="pickaxe"{tr}>'
            f'<line x1="{x}" y1="{y_top}" x2="{x}" y2="{y_bot}" stroke="{WARN}" stroke-width="15" stroke-linecap="round"/>'
            f'<path d="{head}" fill="{MUTED}"/><path d="{shade}" fill="{OUTL}"/>'
            f'<rect x="{x - 12}" y="{y_top - 8}" width="24" height="30" rx="7" fill="{OUTL}"/>'
            f'<rect x="{x - 8}" y="{y_top + 78}" width="16" height="9" rx="3" fill="{EMBER_P}"/>'
            f'<rect x="{x - 8}" y="{y_top + 126}" width="16" height="9" rx="3" fill="{EMBER_P}"/></g>')


