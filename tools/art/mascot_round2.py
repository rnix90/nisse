def cap(shape, shade, x, y, s=1.0, flip=False, band=True):
    """A cap standing on band line y with its base starting at x; the band is the darker Ember strip."""
    w = 170 * s
    tr = f"translate({x + (w if flip else 0):.1f} {y}) scale({-s if flip else s} {s})"
    out = (f'<g transform="{tr}"><path d="{shape}" fill="{EMBER}"/><path d="{shade}" fill="{EMBER_P}"/></g>')
    if band:
        out += f'<rect x="{x - 10 * s:.1f}" y="{y - 15 * s:.1f}" width="{w + 20 * s:.1f}" height="{30 * s:.1f}" rx="{15 * s:.1f}" fill="{EMBER_P}"/>'
    return out


