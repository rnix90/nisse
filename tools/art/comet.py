"""N-404: the comet busy spinner.

How Plasma uses it (spiked 2026-11-15, see docs/busy-widget-notes.md): the splash QML (Fedora's and Breeze's) loads
`images/busywidget.svgz` as a plain Image at 2 grid units and turns the whole image with a RotationAnimator, 0 to 360
degrees in 2000 ms, looping. The animation is therefore not in the file: this is ONE static drawing that must look right
while it turns, centered on its view box so it rotates cleanly. Qt's SVG loader draws it, so it is plain flat shapes: one
color, no masks, no gradients, no opacity.

The design (Bert's pick): a comet alone, all Paper (no Ember). A round head on a circle and a tapered tail curving behind
it, separated from the head by a thin see-through curve that hugs the head, the same kind of line as the horizon curve
of the logo. It turns clockwise, so the head leads and the tail trails counter-clockwise.

    python tools/art/comet.py            writes assets/art/comet/ (svg forms, busywidget.svgz, frame, sheet.png)
"""
import base64
import gzip
import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "tools" / "logo"))
import build_n  # noqa: E402

NMARK = build_n.B          # the logo build module: the hat and the n mark come from there
PAPER, INK = NMARK.PAPER, NMARK.INK
OUT = ROOT / "assets" / "art" / "comet"

HEADER = ('<?xml version="1.0" encoding="UTF-8"?>\n<!-- SPDX-License-Identifier: GPL-2.0-or-later -->\n'
          '<!-- Generated by tools/art/comet.py (N-404). One flat color and plain shapes only, so Qt draws it. -->\n')

# ---- the design, in the 136 unit square Fedora's busy widget uses
SIZE = 136.0
CX = CY = SIZE / 2
ORBIT_R = 54.0              # the head rides this circle; the circle is centered on the view box
HEAD_R = 9.0
GAP = 3.6                   # the see-through curve between head and tail (the logo horizon line is about 2% of its disc)
TAIL_W0 = 18.0              # the tail is as wide as the head where it starts
SPAN = math.radians(175)    # how far round the circle the tail reaches
TAPER = 1.15                # a little more than linear: the tail narrows quickly then lingers
SAMPLES = 90


def _pos(theta, r):
    """A point at angle theta clockwise from twelve o'clock, radius r from the center."""
    return (CX + r * math.sin(theta), CY - r * math.cos(theta))


HEAD = _pos(0.0, ORBIT_R)


def _width(phi):
    return TAIL_W0 * max(0.0, 1.0 - phi / SPAN) ** TAPER


def _edge(phi, side):
    """The tail's outer (side +1) or inner (side -1) edge at phi radians behind the head."""
    return _pos(-phi, ORBIT_R + side * _width(phi) / 2)


def _start(side):
    """Where the tail begins on one edge: the first point outside the gap circle round the head (bisection)."""
    want = HEAD_R + GAP
    lo, hi = 0.0, SPAN
    for _ in range(80):
        mid = (lo + hi) / 2
        if math.dist(_edge(mid, side), HEAD) < want:
            lo = mid
        else:
            hi = mid
    return hi


def _fmt(p):
    return f"{p[0]:.2f} {p[1]:.2f}"


def tail_path():
    """The tail as one closed path: out along the outer edge, back along the inner edge, then an arc concentric with the head."""
    o0, i0 = _start(+1), _start(-1)
    outer = [_edge(o0 + (SPAN - o0) * k / SAMPLES, +1) for k in range(SAMPLES + 1)]
    inner = [_edge(i0 + (SPAN - i0) * k / SAMPLES, -1) for k in range(SAMPLES + 1)]
    p_inner, p_outer = inner[0], outer[0]
    cross = (p_inner[0] - HEAD[0]) * (p_outer[1] - HEAD[1]) - (p_inner[1] - HEAD[1]) * (p_outer[0] - HEAD[0])
    sweep = 1 if cross > 0 else 0
    r = HEAD_R + GAP
    d = "M" + _fmt(outer[0]) + " L" + " L".join(_fmt(p) for p in outer[1:])
    d += " L" + " L".join(_fmt(p) for p in reversed(inner[:-1]))
    d += f" A{r:.2f} {r:.2f} 0 0 {sweep} {_fmt(outer[0])} Z"
    return d


def geometry():
    o0, i0 = _start(+1), _start(-1)
    pts = [_edge(o0 + (SPAN - o0) * k / 400, +1) for k in range(401)] + [_edge(i0 + (SPAN - i0) * k / 400, -1) for k in range(401)]
    dists = [math.dist(p, HEAD) for p in pts]
    extent = max([math.dist((CX, CY), p) for p in pts] + [ORBIT_R + HEAD_R])
    start_w = math.dist(_edge(o0, +1), _edge(o0, -1))
    return dict(cx=CX, cy=CY, orbit_r=ORBIT_R, head=HEAD, head_r=HEAD_R, gap=GAP, tail_points=pts,
                min_tail_distance=min(dists), max_extent=extent, width_at_head=max(start_w, _width(o0)),
                width_at_end=_width(SPAN), tail_end_theta=-SPAN, span=SPAN)


def doc(w, h, label, body):
    return (HEADER + f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}" '
            f'role="img" aria-label="{label}">\n  <title>{label}</title>\n  {body}\n</svg>\n')


def ring(fill):
    """The spinner itself: a head and a tail on the orbit, nothing else."""
    return (f'<g id="nisse-comet-ring" fill="{fill}"><circle id="head" cx="{HEAD[0]:.2f}" cy="{HEAD[1]:.2f}" r="{HEAD_R}"/>'
            f'<path id="tail" d="{tail_path()}"/></g>')


def frame_body(angle=40):
    """A static preview frame: the n with its hat inside the comet ring, the comet caught part way round."""
    s = 3.2
    return (f'<rect width="512" height="512" fill="{INK}"/>'
            f'<g transform="translate({256 - SIZE / 2 * s:.1f} {256 - SIZE / 2 * s:.1f}) scale({s}) rotate({angle} {CX} {CY})">{ring(PAPER)}</g>'
            f'<g transform="translate(128 128) scale(.5)">{build_n.mark(PAPER)}</g>')


def build_forms():
    forms = {
        "nisse-comet": doc(136, 136, "nisse comet busy spinner", ring(PAPER)),
        "nisse-comet-ink": doc(136, 136, "nisse comet busy spinner, ink", ring(INK)),
        "nisse-comet-black": doc(136, 136, "nisse comet busy spinner, black", ring("#000000")),
        "nisse-comet-white": doc(136, 136, "nisse comet busy spinner, white", ring("#ffffff")),
        "nisse-comet-symbolic": doc(136, 136, "nisse comet busy spinner, symbolic", ring("currentColor")),
        "nisse-comet-frame": doc(512, 512, "nisse comet, preview frame with the n", frame_body()),
    }
    return forms


def build_svgz():
    """The Paper spinner as a .svgz, the name and shape Plasma's splash expects (images/busywidget.svgz)."""
    return gzip.compress(build_forms()["nisse-comet"].encode("ascii"), mtime=0)


def _data_uri(svg):
    return "data:image/svg+xml;base64," + base64.b64encode(svg.encode("ascii")).decode()


def build_sheet():
    """Eight turns of the spinner, the sizes it is really shown at, and the preview frame."""
    forms = build_forms()
    w, h = 1840, 1240
    p = [f'<rect width="{w}" height="{h}" fill="{INK}"/>']

    def img(svg, x, y, wd, ht):
        return f'<image href="{_data_uri(svg)}" x="{x}" y="{y}" width="{wd}" height="{ht}"/>'

    def label(x, y, text, size=26, fill=PAPER):
        return f'<text x="{x}" y="{y}" font-family="Nunito, sans-serif" font-size="{size}" fill="{fill}">{text}</text>'

    p.append(label(40, 56, "the spinner turning clockwise, a frame every 45 degrees", 30))
    for k in range(8):
        x = 40 + (k % 4) * 440
        y = 90 + (k // 4) * 330
        rot = doc(136, 136, "turn", f'<g transform="rotate({k * 45} {CX} {CY})">{ring(PAPER)}</g>')
        p.append(f'<rect x="{x}" y="{y}" width="300" height="300" fill="#000000"/>' + img(rot, x, y, 300, 300) + label(x + 320, y + 160, f"{k * 45} deg", 24))
    p.append(label(40, 800, "as the splash shows it: 36, 72 and 136 px, on black and on Ink", 26))
    for bg, y in (("#000000", 830), (INK, 1000)):
        p.append(f'<rect x="40" y="{y}" width="900" height="150" fill="{bg}"/>')
        x = 70
        for px in (36, 72, 136):
            p.append(img(forms["nisse-comet"], x, y + (150 - px) / 2, px, px))
            x += px + 60
    p.append(label(990, 800, "preview frame", 26) + img(forms["nisse-comet-frame"], 990, 830, 330, 330))
    return doc(w, h, "nisse comet spinner, frame sheet", "".join(p)), w, h


def main():
    from playwright.sync_api import sync_playwright  # noqa: F401  (the Raster helper needs it)
    forms = build_forms()
    for name, svg in forms.items():
        NMARK.write(OUT / "svg" / f"{name}.svg", svg)
    NMARK.write(OUT / "busywidget.svgz", build_svgz())
    sheet, w, h = build_sheet()
    NMARK.write(OUT / "sheet.svg", sheet)
    with NMARK.Raster() as R:
        NMARK.write(OUT / "png" / "nisse-comet-frame-512.png", R.png(forms["nisse-comet-frame"], 512, 512))
        NMARK.write(OUT / "sheet.png", R.png(sheet, w, h))
    print(f"wrote {len(forms)} svgs, busywidget.svgz, the frame png and sheet.png to {OUT}")


if __name__ == "__main__":
    sys.exit(main())
