"""The panel's system tray icon in every state (ledger N-413): one monochrome mark, six states.

The mark is the nisse n with its tipped hat (N-403, the panel app's own icon). Plasma recolors a symbolic icon to the panel's text
color, so each file is one color (`currentColor`) with KDE's `current-color-scheme` style and nothing else: no gradients, no
filters, no second color. The states are told apart by shape, because the tray is monochrome:

    idle        the n alone
    busy        the n inside the comet ring (the N-404 spinner, the same ring the Plasma splash uses)
    needs-you   a solid disc with an exclamation mark cut out, top right (an approval waits)
    unread      a small solid dot, top right (a turn finished while you were elsewhere)
    paused      two pause bars, top right (the kill switch is on); bars, not a disc, so it never looks like needs-you at 22 px
    offline     a ring with a slash through it, top right (the daemon cannot be reached)

A badge leaves a clear gap around itself (a mask), so it never merges with the n at 16 px.

    python tools/art/tray_icons.py [--out DIR]    writes DIR/svg/nisse-tray-<state>-symbolic.svg, previews and sheet.png (Playwright)
"""
import base64
import importlib.util
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))
OUT = ROOT / "assets" / "art" / "tray"
LF = chr(10)

_spec = importlib.util.spec_from_file_location("nisse_build_n", ROOT / "tools" / "logo" / "build_n.py")
BUILD_N = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(BUILD_N)
import comet  # noqa: E402

PAPER = "#f6f2e9"
INK = "#1b2330"
STATES = ("idle", "busy", "needs-you", "unread", "paused", "offline")
TITLES = {
    "idle": "idle",
    "busy": "busy (working)",
    "needs-you": "needs you (an approval waits)",
    "unread": "unread (a turn finished)",
    "paused": "paused (kill switch on)",
    "offline": "offline (daemon unreachable)",
}
GAP = 18                       # clear space kept around a badge or the slash, in the 512 box
HEADER = ('<?xml version="1.0" encoding="UTF-8"?>' + LF + '<!-- SPDX-License-Identifier: GPL-2.0-or-later -->' + LF
          + '<!-- Generated by tools/art/tray_icons.py (N-413). The n is outlined from Nunito (SIL OFL 1.1); the hat is the logo HAT. -->' + LF)

# where things sit in the 512 box
BADGE_C = (438, 122)
DISC_R = 72
DOT_R = 62
BARS = ((394, 68, 32, 108), (450, 68, 32, 108))      # x, y, width, height: the pause sign
RING_R = 58                    # the offline badge: a ring this big (centerline) ...
RING_W = 20                    # ... this thick, with a slash of the same weight


def n_mark(scale=0.9, shift=(0, 0)):
    """The n with its hat, drawn with currentColor, scaled about the middle of the box."""
    cx, cy = 256 + shift[0], 256 + shift[1]
    g = BUILD_N.mark("currentColor")
    g = g.replace('fill="currentColor"', 'class="ColorScheme-Text" fill="currentColor"')
    return f'<g transform="translate({cx - 256 * scale:.2f} {cy - 256 * scale:.2f}) scale({scale})">{g}</g>'


def ring():
    """The comet of the busy spinner (assets/art/comet), as one currentColor shape at the full box."""
    k = 512 / comet.SIZE
    return (f'<g transform="scale({k:.5f})" class="ColorScheme-Text" fill="currentColor">'
            f'<path d="{comet.tail_path()}"/><circle cx="{comet.HEAD[0]:.2f}" cy="{comet.HEAD[1]:.2f}" r="{comet.HEAD_R}"/></g>')


def masked(body, shapes, mid):
    """`body` with every shape in `shapes` (SVG drawn in black) cut out of it: the clear gap around a badge."""
    return (f'<mask id="{mid}" maskUnits="userSpaceOnUse" x="0" y="0" width="512" height="512"><rect width="512" height="512" fill="#fff"/>'
            f'{shapes}</mask><g mask="url(#{mid})">{body}</g>')


def exclamation():
    cx, cy = BADGE_C
    return (f'<rect x="{cx - 11}" y="{cy - 44}" width="22" height="52" rx="11" fill="#000"/>'
            f'<circle cx="{cx}" cy="{cy + 32}" r="13" fill="#000"/>')


def build(state):
    style = f'<style type="text/css" id="current-color-scheme">.ColorScheme-Text {{ color:{PAPER}; }}</style>'
    cx, cy = BADGE_C
    if state == "idle":
        body = n_mark()
    elif state == "busy":
        body = ring() + n_mark(0.6)
    elif state == "unread":
        body = (masked(n_mark(), f'<circle cx="{cx}" cy="{cy}" r="{DOT_R + GAP}" fill="#000"/>', "gap")
                + f'<circle cx="{cx}" cy="{cy}" r="{DOT_R}" class="ColorScheme-Text" fill="currentColor"/>')
    elif state == "needs-you":
        disc = (f'<mask id="cut" maskUnits="userSpaceOnUse" x="0" y="0" width="512" height="512"><rect width="512" height="512" fill="#fff"/>'
                f'{exclamation()}</mask><circle cx="{cx}" cy="{cy}" r="{DISC_R}" class="ColorScheme-Text" fill="currentColor" mask="url(#cut)"/>')
        body = masked(n_mark(), f'<circle cx="{cx}" cy="{cy}" r="{DISC_R + GAP}" fill="#000"/>', "gap") + disc
    elif state == "paused":
        bars = "".join(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="10" class="ColorScheme-Text" fill="currentColor"/>' for x, y, w, h in BARS)
        gaps = "".join(f'<rect x="{x - GAP}" y="{y - GAP}" width="{w + 2 * GAP}" height="{h + 2 * GAP}" rx="{10 + GAP}" fill="#000"/>' for x, y, w, h in BARS)
        body = masked(n_mark(), gaps, "gap") + bars
    elif state == "offline":
        k = RING_R * 0.7071
        badge = (f'<circle cx="{cx}" cy="{cy}" r="{RING_R}" fill="none" stroke-width="{RING_W}" class="ColorScheme-Text" stroke="currentColor"/>'
                 f'<line x1="{cx - k:.1f}" y1="{cy + k:.1f}" x2="{cx + k:.1f}" y2="{cy - k:.1f}" stroke-width="{RING_W}" stroke-linecap="butt" '
                 f'class="ColorScheme-Text" stroke="currentColor"/>')
        body = masked(n_mark(), f'<circle cx="{cx}" cy="{cy}" r="{RING_R + RING_W // 2 + GAP}" fill="#000"/>', "gap") + badge
    else:
        raise KeyError(state)
    title = f"nisse tray icon, {TITLES[state]}, symbolic"
    return (HEADER + f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512" role="img" aria-label="{title}">'
            + LF + f'  <title>{title}</title>' + LF + f'  {style}' + LF + f'  {body}' + LF + '</svg>' + LF)


def build_all():
    return {state: build(state) for state in STATES}


def file_name(state):
    return f"nisse-tray-{state}-symbolic.svg"


def _uri(svg, color=None):
    if color:
        svg = svg.replace(f"color:{PAPER};", f"color:{color};")
    return "data:image/svg+xml;base64," + base64.b64encode(svg.encode("ascii")).decode()


def _page(inner):
    font = base64.b64encode((ROOT / "assets" / "fonts" / "Nunito" / "Nunito[wght].ttf").read_bytes()).decode()
    return (f'<html><head><style>@font-face{{font-family:"Nunito";src:url(data:font/ttf;base64,{font}) format("truetype");font-weight:200 1000;}}'
            f'body{{margin:0}}</style></head><body>{inner}</body></html>')


def sheet_html(svgs):
    """Each state at the sizes a tray uses, on a dark and a light panel, with a large copy to read the shape."""
    def strip(svg, bg, fg):
        u = _uri(svg, fg)
        imgs = "".join(f'<img src="{u}" width="{s}" height="{s}">' for s in (16, 22, 32))
        return (f'<div style="background:{bg};padding:10px 14px;display:flex;gap:14px;align-items:center;border-radius:8px">{imgs}</div>')
    rows = []
    for state in STATES:
        svg = svgs[state]
        big = f'<img src="{_uri(svg, PAPER)}" width="128" height="128" style="background:{INK};border-radius:12px">'
        bigl = f'<img src="{_uri(svg, INK)}" width="128" height="128" style="background:{PAPER};border-radius:12px">'
        rows.append(f'<div style="display:grid;grid-template-columns:230px 130px 130px 190px 190px;gap:18px;align-items:center;margin:0 0 14px">'
                    f'<div style="font:700 21px Nunito;color:{PAPER}">{TITLES[state]}</div>{big}{bigl}'
                    f'{strip(svg, "#222c3b", PAPER)}{strip(svg, "#f6f2e9", INK)}</div>')
    head = (f'<div style="font:800 30px Nunito;color:{PAPER};margin-bottom:6px">nisse tray icon: six states, one monochrome mark (N-413)</div>'
            f'<div style="font:400 18px Nunito;color:#aab1bd;margin-bottom:20px">Large copies at 128 px, then the real sizes 16, 22 and 32 px on a dark and on a light panel. '
            f'Plasma recolors the icon to the panel text color.</div>')
    return f'<div style="width:1020px;padding:24px;background:{INK}">{head}{"".join(rows)}</div>'


def main(argv=None):
    from playwright.sync_api import sync_playwright
    argv = sys.argv[1:] if argv is None else argv
    out = pathlib.Path(argv[argv.index("--out") + 1]) if "--out" in argv else OUT
    (out / "svg").mkdir(parents=True, exist_ok=True)
    svgs = build_all()
    for state, svg in svgs.items():
        (out / "svg" / file_name(state)).write_text(svg, encoding="ascii", newline=LF)
    with sync_playwright() as p:
        browser = p.chromium.launch()
        page = browser.new_page(viewport={"width": 1070, "height": 1000})
        page.set_content(_page(sheet_html(svgs)))
        page.wait_for_timeout(500)
        (out / "sheet.png").write_bytes(page.screenshot(full_page=True))
        browser.close()
    print(f"wrote {len(svgs)} tray icons and the sheet to {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
