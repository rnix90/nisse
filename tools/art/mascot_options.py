def doc(w, h, title, body, defs=""):
    d = f"  <defs>{defs}</defs>\n" if defs else ""
    return (HEADER + f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}" '
            f'role="img" aria-label="{title}">\n  <title>{title}</title>\n{d}  {body}\n</svg>\n')


def head_doc(title, body):
    clip = f'<clipPath id="disc"><circle cx="256" cy="256" r="236"/></clipPath>'
    return doc(HEAD_BOX, HEAD_BOX, title,
               f'<circle cx="256" cy="256" r="236" fill="{SURF}"/>\n  <g clip-path="url(#disc)">{body}</g>', clip)


def pickaxe(x_top, y_top, x_bot, y_bot, metal=MUTED, wood=WARN, flip=False):
    """A pickaxe as a group with id pickaxe: a handle and a crescent head on top, around (x_top, y_top)."""
    s = -1 if flip else 1
    head = (f"M{x_top - 52 * s} {y_top + 12} C{x_top - 24 * s} {y_top - 28} {x_top + 28 * s} {y_top - 28} "
            f"{x_top + 54 * s} {y_top + 8} C{x_top + 28 * s} {y_top - 6} {x_top + 8 * s} {y_top - 4} "
            f"{x_top} {y_top + 8} C{x_top - 10 * s} {y_top - 2} {x_top - 32 * s} {y_top - 2} {x_top - 52 * s} {y_top + 12} Z")
    return (f'<g id="pickaxe"><line x1="{x_top}" y1="{y_top}" x2="{x_bot}" y2="{y_bot}" stroke="{wood}" '
            f'stroke-width="12" stroke-linecap="round"/><path d="{head}" fill="{metal}"/></g>')


