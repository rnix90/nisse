OPTIONS = {
    "a": ("1", "classic", a_head, a_figure),
    "b": ("2", "wee", b_head, b_figure),
    "c": ("3", "wanderer", c_head, c_figure),
    "d": ("4", "faceted", d_head, d_figure),
}


def build_all():
    out = {}
    for key, (_, _, head, figure) in OPTIONS.items():
        out[f"{key}-head"] = head()
        out[f"{key}-figure"] = figure()
    return out


def _inner(svg):
    """The drawing of one SVG as a group body (drops the document wrapper, keeps its defs)."""
    start = svg.index("<defs>") if "<defs>" in svg else svg.index("<title>")
    inner = svg[start:svg.rindex("</svg>")]
    return inner.replace("<title>", "<title>", 1)


def build_sheet():
    col_w, margin = 440, 40
    w = margin * 2 + col_w * 4
    head_scale, fig_scale = 0.8, 0.86
    h = 1180
    parts = []
    for i, (key, (num, name, _, _)) in enumerate(OPTIONS.items()):
        x0 = margin + i * col_w
        svgs = {"head": build_all()[f"{key}-head"], "figure": build_all()[f"{key}-figure"]}
        # distinct clip ids per option: the head badges all define one
        head_inner = _inner(svgs["head"]).replace('id="disc"', f'id="disc-{key}"').replace('url(#disc)', f'url(#disc-{key})')
        fig_inner = _inner(svgs["figure"])
        parts.append(
            f'<g transform="translate({x0 + 15} 120) scale({head_scale})">{head_inner}</g>'
            f'<g transform="translate({x0 + 48} 570) scale({fig_scale})">{fig_inner}</g>'
            f'<text x="{x0 + col_w / 2}" y="86" font-family="Nunito, sans-serif" font-size="56" font-weight="800" '
            f'fill="{PAPER}" text-anchor="middle">{num}</text>'
            f'<text x="{x0 + col_w / 2}" y="1150" font-family="Nunito, sans-serif" font-size="30" '
            f'fill="{MUTED}" text-anchor="middle">{name}</text>')
    body = f'<rect width="{w}" height="{h}" fill="{INK}"/>' + "".join(parts)
    return doc(w, h, "nisse gnome mascot, round 1: four options", body)


def main():
    from playwright.sync_api import sync_playwright
    OUT.mkdir(parents=True, exist_ok=True)
    for name, svg in build_all().items():
        (OUT / f"{name}.svg").write_text(svg, encoding="ascii", newline="\n")
    sheet = build_sheet()
    (OUT / "sheet.svg").write_text(sheet, encoding="ascii", newline="\n")
    uri = "data:image/svg+xml;base64," + base64.b64encode(sheet.encode("ascii")).decode()
    with sync_playwright() as p:
        b = p.chromium.launch()
        pg = b.new_page(viewport={"width": 1840, "height": 1180})
        pg.set_content(f'<html><body style="margin:0"><img src="{uri}" width="1840" height="1180" style="display:block"></body></html>')
        pg.wait_for_function("document.images[0].complete")
        (OUT / "sheet.png").write_bytes(pg.screenshot(clip={"x": 0, "y": 0, "width": 1840, "height": 1180}))
        b.close()
    print(f"wrote {len(build_all())} drawings, sheet.svg and sheet.png to {OUT}")


if __name__ == "__main__":
    sys.exit(main())
