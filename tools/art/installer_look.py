"""The installer's look (ledger N-411): the Cockpit branding folder that gives the Anaconda WebUI the nisse colors and logo.

The installer you see on the live image is the Anaconda WebUI, a Cockpit page. Cockpit takes its colors and logo from
/usr/share/cockpit/branding/<os-release ID>/ (then each ID_LIKE). nisse had no such folder, so the installer used Fedora's
(ID_LIKE=fedora): a blue header and a Fedora logo. This builds the nisse folder from the Ember palette:

  branding.css         the palette for both looks. Dark: Ink page, Ember fills carry Ink text (Paper on Ember is only 3.1:1).
                       Light: the page and Paper, the darker accent carries Paper. Brand tokens and the page tokens are
                       set on :root (set on .anaconda they never reached the page background); the header band and the
                       logo are overridden with rules that out-rank the installer's own.
  logo.png             the 128 px app tile (the installer turns a bare logo into a white glyph; ours is a finished tile)
  favicon.ico          16, 32, 48 and 64 px of the tile
  apple-touch-icon.png 180 px

Every color is a palette color; the hover and pressed shades of the light accent are color-mix of palette colors.
tools/logo/build_system.py calls write() so the folder is part of assets/logo/system. Needs: Pillow.
"""
import io
import json
import pathlib

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[2]
PALETTE_FILE = ROOT / "assets" / "palette" / "ember.json"
TILE = ROOT / "assets" / "logo" / "png" / "nisse-app-tile-256.png"
BRAND_DIR = "nisse"
FILES = ("branding.css", "logo.png", "favicon.ico", "apple-touch-icon.png")


def tok(pal, dotted):
    group, name = dotted.split(".", 1)
    return pal[group][name]["hex"].lower()


def mix(a, pct, b):
    """A CSS color-mix of two palette colors (the browser computes it)."""
    return f"color-mix(in srgb, {a} {pct}%, {b})"


def css(pal):
    d = lambda n: tok(pal, "dark." + n)  # noqa: E731
    l = lambda n: tok(pal, "light." + n)  # noqa: E731
    return f"""/* SPDX-License-Identifier: GPL-2.0-or-later */
/* The installer's look (generated by tools/art/installer_look.py from assets/palette/ember.json, ledger N-411). */
#badge {{
    inline-size: 225px;
    block-size: 80px;
    background-image: url("logo.png");
    background-size: contain;
    background-repeat: no-repeat;
}}

#brand::before {{
    content: "${{NAME}} <b>${{VARIANT}}</b>";
}}

.anaconda {{
    --brand-default-light: {d("accent-hover")};
    --brand-default: {d("accent")};
    --brand-default-dark: {d("accent-pressed")};

    .logo {{
        background-image: url("logo.png");
        /* the installer turns a logo into a white glyph with a filter; nisse's is a finished tile */
        filter: none;
        mix-blend-mode: normal;
    }}
}}

/* light look: the document colors, and the darker accent, which carries Paper text */
:root:not(.pf-v6-theme-dark) {{
    --nisse-header-text: {l("on-accent")};
    --pf-t--global--color--brand--default: {l("accent")};
    --pf-t--global--color--brand--hover: {mix(l("accent"), 80, l("text"))};
    --pf-t--global--color--brand--clicked: {mix(l("accent"), 62, l("text"))};
    --pf-t--global--text--color--brand--default: {l("accent")};
    --pf-t--global--text--color--on-brand--default: {l("on-accent")};
    --pf-t--global--text--color--on-brand--hover: {l("on-accent")};
    --pf-t--global--text--color--on-brand--clicked: {l("on-accent")};
    --pf-t--global--icon--color--brand--default: {l("accent")};
    --pf-t--global--text--color--link--default: {l("accent")};
    --pf-t--global--text--color--link--hover: {mix(l("accent"), 80, l("text"))};
    --pf-t--global--text--color--link--visited: {l("visited")};
    --pf-t--global--background--color--primary--default: {l("page")};
    --pf-t--global--background--color--secondary--default: {l("paper")};
    --pf-t--global--text--color--regular: {l("text")};
    --pf-t--global--text--color--subtle: {l("text-muted")};
    --pf-t--global--border--color--default: {l("outline")};
}}

/* dark look: the desktop's colors; an Ember fill carries Ink text */
:root.pf-v6-theme-dark {{
    --nisse-header-text: {d("on-accent")};
    --pf-t--global--color--brand--default: {d("accent")};
    --pf-t--global--color--brand--hover: {d("accent-hover")};
    --pf-t--global--color--brand--clicked: {d("accent-pressed")};
    --pf-t--global--text--color--brand--default: {d("accent-text")};
    --pf-t--global--text--color--on-brand--default: {d("on-accent")};
    --pf-t--global--text--color--on-brand--hover: {d("on-accent")};
    --pf-t--global--text--color--on-brand--clicked: {d("on-accent")};
    --pf-t--global--icon--color--brand--default: {d("accent-text")};
    --pf-t--global--text--color--link--default: {d("accent-text")};
    --pf-t--global--text--color--link--hover: {mix(d("accent-text"), 80, d("text"))};
    --pf-t--global--text--color--link--visited: {d("visited")};
    --pf-t--global--background--color--primary--default: {d("base")};
    --pf-t--global--background--color--secondary--default: {d("surface")};
    --pf-t--global--background--color--control--default: {d("surface-2")};
    --pf-t--global--background--color--floating--default: {d("surface-2")};
    --pf-t--global--background--color--action--plain--hover: {d("surface-2")};
    --pf-t--global--text--color--regular: {d("text")};
    --pf-t--global--text--color--subtle: {d("text-muted")};
    --pf-t--global--border--color--default: {d("outline")};
}}

/* the header band: the installer paints it from --brand-default-light to --brand-default with white text; this out-ranks
   its rule (0,4,0 against 0,3,0) and sets the text the palette allows on the fill */
:root .pf-v6-c-page__main-group > .pf-v6-c-page__main-section:first-child {{
    --_text: var(--nisse-header-text);
    background: radial-gradient(circle at 2.5rem, var(--brand-default-light) 32px, var(--brand-default) 100%);

    .pf-v6-c-content {{
        --pf-v6-c-content--Color: var(--_text);
    }}
}}

/* the light look's gradient ends (the dark look takes the three above): the accent, and a darker mix with Ink; both carry Paper
   text (a lighter end would not: Paper on the accent is 5.4:1 and falls under 4.5 with a little Paper mixed in) */
:root:not(.pf-v6-theme-dark) .anaconda {{
    --brand-default-light: {l("accent")};
    --brand-default: {mix(l("accent"), 88, l("text"))};
    --brand-default-dark: {mix(l("accent"), 70, l("text"))};
}}
"""


def tile(size):
    return Image.open(TILE).convert("RGBA").resize((size, size), Image.LANCZOS)


def _png(img):
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    return buf.getvalue()


def logo_png():
    return _png(tile(128))


def apple_touch_png():
    return _png(tile(180))


def favicon_ico():
    buf = io.BytesIO()
    tile(256).save(buf, format="ICO", sizes=[(16, 16), (32, 32), (48, 48), (64, 64)])
    return buf.getvalue()


def write(out):
    """Write the branding folder under `out` (the image root): out/usr/share/cockpit/branding/nisse/*."""
    pal = json.loads(PALETTE_FILE.read_text(encoding="ascii"))
    folder = pathlib.Path(out) / "usr" / "share" / "cockpit" / "branding" / BRAND_DIR
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "branding.css").write_text(css(pal), encoding="ascii", newline="\n")
    (folder / "logo.png").write_bytes(logo_png())
    (folder / "favicon.ico").write_bytes(favicon_ico())
    (folder / "apple-touch-icon.png").write_bytes(apple_touch_png())
    return folder


if __name__ == "__main__":
    print(write(ROOT / "assets" / "logo" / "system"))
