"""N-402, round 5: the master gnome and four tool and hand options on it.

Bert's pick from round 4: the gumdrop body (cap over one round Paper beard-body) with the face of the robe (a skin
band under the cap with two eyes, and a nose that sits on the line between skin and beard). The four options differ
only in the tool and how the hands hold it:
  1 pickaxe, leaning, one hand on the handle      2 pickaxe, carried across the body in two hands
  3 hammer, raised in one arm                     4 lantern, hanging from one hand on an arm
Same rules as round 4: one width, the head touches the body, flat shapes, at most six palette colors.

    python tools/art/mascot_round5.py            writes assets/art/mascot-round5/*.svg, sheet.png
"""
import base64
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from mascot_options import (DIV, EMBER, EMBER_P, EMBER_T, FIG_H, FIG_W, HEAD_BOX, INK, MUTED, PAPER,  # noqa: E402
                            SURF, SURF2)
from mascot_round4 import PICK_HALF_SPAN, along, beard_body, boots, cap, hand, pick  # noqa: E402,F401

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "assets" / "art" / "mascot-round5"

HEADER = '<?xml version="1.0" encoding="UTF-8"?>\n<!-- SPDX-License-Identifier: GPL-2.0-or-later -->\n' \
         '<!-- Generated by tools/art/mascot_round5.py (N-402 round 5). Ember palette only. -->\n'


def doc(w, h, title, body, defs=""):
    d = f"  <defs>{defs}</defs>\n" if defs else ""
    return (HEADER + f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}" '
            f'role="img" aria-label="{title}">\n  <title>{title}</title>\n{d}  {body}\n</svg>\n')


def spec():
    """The master's one width and where the head ends and the body begins (y)."""
    return dict(cap_w=180, face_w=180, beard_w=180, cap_base=300, head_bottom=354, body_top=354)


def cap_top():
    sp = spec()
    return sp["cap_base"] - 192 * sp["cap_w"] / 170


def master_art():
    """The master with no feet, hands or tool: the cap, the robe's face and the round beard-body."""
    sp = spec()
    x0 = 200 - sp["face_w"] / 2
    base = sp["cap_base"]
    eyes = "".join(f'<circle id="eye" cx="{200 + dx}" cy="{base + 28}" r="9" fill="{INK}"/>' for dx in (-38, 38))
    return (f'<rect id="face" x="{x0}" y="{base - 8}" width="{sp["face_w"]}" height="78" rx="24" fill="{EMBER_T}"/>'
            + beard_body(sp["beard_w"], sp["body_top"], 534, PAPER)
            + f'<circle id="nose" cx="200" cy="{sp["body_top"] + 2}" r="20" fill="{EMBER}"/>' + eyes
            + cap(sp["cap_w"], base))


def arm(x1, y1, x2, y2):
    return f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" stroke="{EMBER_T}" stroke-width="20" stroke-linecap="round"/>'


def hammer(x, y, length, tilt=4):
    """Group id hammer: a handle and a block head of flat steel."""
    return (f'<g id="hammer" transform="rotate({tilt} {x} {y})">'
            f'<line x1="{x}" y1="{y - 4}" x2="{x}" y2="{y + length}" stroke="{EMBER_P}" stroke-width="15" stroke-linecap="round"/>'
            f'<rect x="{x - 40}" y="{y - 36}" width="80" height="44" rx="9" fill="{MUTED}"/></g>')


def lantern(x, y):
    """Group id lantern: a bail from the hand, a steel frame and a warm glow. (x, y) is the hand."""
    return (f'<g id="lantern"><path d="M{x - 18} {y + 40} Q{x} {y - 12} {x + 18} {y + 40}" fill="none" stroke="{MUTED}" stroke-width="5" stroke-linecap="round"/>'
            f'<rect x="{x - 25}" y="{y + 34}" width="50" height="12" rx="4" fill="{MUTED}"/>'
            f'<rect x="{x - 22}" y="{y + 44}" width="44" height="52" rx="8" fill="{MUTED}"/>'
            f'<rect x="{x - 14}" y="{y + 52}" width="28" height="36" rx="5" fill="{EMBER_T}"/></g>')


# the four tool and hand options: each returns what is drawn over the master (hands, arms, tool)
def pose_pick_lean():
    px, py = 306, 330
    hx, hy = along(px, py, 100)
    return pick(px, py, 214, head=MUTED) + hand(hx, hy) + hand(104, 452)


def pose_pick_carry():
    # the pickaxe carried flat across the body at belly height, the head to the right, a hand on each side of the belly
    px, py = 338, 440
    h1, h2 = along(px, py, 78, 90), along(px, py, 196, 90)
    return pick(px, py, 300, head=MUTED, tilt=90) + hand(*h1) + hand(*h2)


def pose_hammer_up():
    hx, hy = along(330, 292, 108, 4)
    return hand(104, 452) + arm(286, 424, hx, hy) + hammer(330, 292, 150) + hand(hx, hy)


def pose_lantern():
    return hand(104, 452) + arm(288, 414, 330, 444) + lantern(330, 444) + hand(330, 444)


POSES = {
    "1": ("pickaxe leaning", pose_pick_lean),
    "2": ("pickaxe carried", pose_pick_carry),
    "3": ("hammer raised", pose_hammer_up),
    "4": ("lantern hanging", pose_lantern),
}


def figure(n):
    name, pose = POSES[n]
    return doc(FIG_W, FIG_H, f"nisse gnome master, tool option {n}: {name}",
               boots(538, 34) + master_art() + pose())


def master_badge():
    s = 1.3
    ty = 40 - cap_top() * s
    clip = '<clipPath id="disc"><circle cx="256" cy="256" r="236"/></clipPath>'
    hill = f'<path d="M0 410 C120 380 200 372 256 374 C330 376 400 384 512 420 V512 H0 Z" fill="{SURF2}"/>'
    body = (f'<circle cx="256" cy="256" r="236" fill="{SURF}"/>\n  <g clip-path="url(#disc)">{hill}'
            f'<g transform="translate({256 - 200 * s:.1f} {ty:.1f}) scale({s})">{master_art()}</g></g>')
    return doc(HEAD_BOX, HEAD_BOX, "nisse gnome master, head badge", body, clip)


def build_all():
    out = {"master-head": master_badge()}
    for n in POSES:
        out[f"{n}-figure"] = figure(n)
    return out


def _inner(svg):
    start = svg.index("<defs>") if "<defs>" in svg else svg.index("<title>")
    return svg[start:svg.rindex("</svg>")]


SHEET_W, SHEET_H = 1840, 1140


def build_sheet():
    allsvg = build_all()
    head = _inner(allsvg["master-head"])
    parts = [f'<g transform="translate(60 70) scale(0.62)">{head}</g>'
             f'<text x="60" y="52" font-family="Nunito, sans-serif" font-size="34" font-weight="800" fill="{PAPER}">master</text>'
             f'<text x="230" y="52" font-family="Nunito, sans-serif" font-size="26" fill="{MUTED}">gumdrop body, robe face</text>']
    for bg, ty in ((SURF, 70), (PAPER, 300)):
        parts.append(f'<rect x="460" y="{ty}" width="1320" height="200" fill="{bg}"/>')
        x = 490
        for w in (96, 48, 24):
            parts.append(f'<g transform="translate({x} {ty + 24 + (96 - w) / 2:.0f}) scale({w / 512:.4f})">{head}</g>')
            x += w + 18
        parts.append(f'<text x="490" y="{ty + 170}" font-family="Nunito, sans-serif" font-size="22" fill="{MUTED if bg == SURF else DIV}">'
                     f'avatar sizes 96, 48 and 24 px</text>')
    for i, (n, (name, _)) in enumerate(POSES.items()):
        x0 = 40 + i * 440
        parts.append(f'<g transform="translate({x0 + 40} 580) scale(0.9)">{_inner(allsvg[f"{n}-figure"])}</g>'
                     f'<text x="{x0 + 30}" y="566" font-family="Nunito, sans-serif" font-size="54" font-weight="800" fill="{PAPER}">{n}</text>'
                     f'<text x="{x0 + 100}" y="566" font-family="Nunito, sans-serif" font-size="30" fill="{MUTED}">{name}</text>')
    body = f'<rect width="{SHEET_W}" height="{SHEET_H}" fill="{INK}"/>' + "".join(parts)
    return doc(SHEET_W, SHEET_H, "nisse gnome master and four tool and hand options", body)


def main():
    from playwright.sync_api import sync_playwright
    OUT.mkdir(parents=True, exist_ok=True)
    for name, svg in build_all().items():
        (OUT / f"{name}.svg").write_text(svg, encoding="ascii", newline="\n")
    sheet = build_sheet()
    (OUT / "sheet.svg").write_text(sheet, encoding="ascii", newline="\n")
    uri = "data:image/svg+xml;base64," + base64.b64encode(sheet.encode("ascii")).decode()
    with sync_playwright() as p:
        b = p.chromium.launch()
        pg = b.new_page(viewport={"width": SHEET_W, "height": SHEET_H})
        pg.set_content(f'<html><body style="margin:0"><img src="{uri}" width="{SHEET_W}" height="{SHEET_H}" style="display:block"></body></html>')
        pg.wait_for_function("document.images[0].complete")
        (OUT / "sheet.png").write_bytes(pg.screenshot(clip={"x": 0, "y": 0, "width": SHEET_W, "height": SHEET_H}))
        b.close()
    print(f"wrote {len(build_all())} drawings, sheet.svg and sheet.png to {OUT}")


if __name__ == "__main__":
    sys.exit(main())
